import assert from "node:assert/strict";
import test from "node:test";
import { createDispatcherHarness } from "../test-support/dispatcher.js";
import { createScenarioRunner } from "../test-support/scenarios.js";
import * as scenarios from "../api/scenarios/index.js";
const path = "/v1/convai/secrets";
const input = { type: "new", name: "Synthetic token", value: "synthetic-only-value" };
test("secret Context atomic CRUD omission defensive copies and dependencies", async () => {
  const { Context } = await import("../api/routes/convai/secrets/_.context.js");
  const context = new Context();
  assert.deepEqual(context.listSecrets().value, { secrets: [], next_cursor: null });
  const created = context.createSecret(input).value!;
  assert.deepEqual(created, { type: "stored", secret_id: "sim-secret-created-1", name: input.name });
  assert.equal(context.secrets.get(created.secret_id)!.value, input.value);
  created.name = "mutation";
  const get = context.getSecret(created.secret_id)!;
  get.used_by.tools.push({ type: "unknown", id: "mutation" });
  const listed = context.listSecrets().value!;
  listed.secrets[0].name = "mutation";
  assert.equal(context.getSecret(created.secret_id)!.name, input.name);
  assert.deepEqual(context.getSecret(created.secret_id)!.used_by.tools, []);
  for (const bad of [null, {}, { ...input, type: "stored" }, { ...input, name: " " }, { ...input, value: "" }, { ...input, permission: "admin" }]) assert.equal(context.createSecret(bad).error, "invalid_secret");
  for (const bad of [{}, { type: "update", name: "x" }, { ...input, type: "update", permission: "admin" }]) {
    assert.equal(context.updateSecret(created.secret_id, bad).error, "invalid_secret");
    assert.equal(context.secrets.get(created.secret_id)!.value, input.value);
  }
  assert.equal(context.nextSecretNumber, 1);
  assert.equal(context.updateSecret(created.secret_id, { type: "update", name: "rotated", value: "synthetic-rotated" }).value!.name, "rotated");
  assert.equal(context.secrets.get(created.secret_id)!.value, "synthetic-rotated");
  assert.equal(JSON.stringify(context.getSecret(created.secret_id)).includes("synthetic-rotated"), false);
  assert.equal(context.deleteSecret(created.secret_id), undefined);
  assert.equal(context.getSecret(created.secret_id), undefined);
  assert.equal(context.deleteSecret("missing"), "secret_not_found");
  assert.equal(context.updateSecret("missing", {}).error, "secret_not_found");
});
test("secret Dispatcher CRUD queries errors omission reset and isolation", async () => {
  const app = await createDispatcherHarness();
  const second = await createDispatcherHarness();
  const send = (method: string, body: unknown, suffix = "") => app.request(path + suffix, { method, headers: { "content-type": "application/json" }, body: JSON.stringify(body) });
  const list = async (query = "") => {
    const response = await app.request(path + query);
    assert.equal(response.status, 200);
    assert.match(response.headers.get("content-type")!, /application\/json/);
    return response.json();
  };
  const baseline = await list();
  assert.equal(baseline.secrets[0].secret_id, "sim-secret");
  const response = await send("POST", input);
  assert.equal(response.status, 200);
  const created = await response.json();
  assert.deepEqual(created, { type: "stored", name: input.name, secret_id: "sim-secret-created-1" });
  assert.equal((await list("?search=Synthetic")).secrets.length, 1);
  assert.equal((await list("?page_size=1")).next_cursor, "1");
  assert.equal((await list("?page_size=1&cursor=1")).secrets[0].secret_id, created.secret_id);
  assert.deepEqual((await list("?cursor=99")).secrets, []);
  const patch = await send("PATCH", { type: "update", name: "Rotated", value: "synthetic-replacement" }, "/" + created.secret_id);
  assert.equal(patch.status, 200);
  assert.deepEqual(await patch.json(), { type: "stored", name: "Rotated", secret_id: created.secret_id });
  const current = await (await app.request(path + "/" + created.secret_id)).json();
  assert.equal(current.name, "Rotated");
  assert.deepEqual(Object.keys(current).sort(), ["name", "secret_id", "type", "used_by"]);
  const after = await list();
  for (const body of [{}, { ...input, value: "" }, { ...input, permission: "admin" }]) assert.equal((await send("POST", body)).status, 400);
  for (const body of [{}, { type: "update", name: "bad" }, { type: "update", name: "bad", value: "x", permission: "admin" }]) assert.equal((await send("PATCH", body, "/" + created.secret_id)).status, 400);
  for (const query of ["?page_size=0", "?page_size=101", "?cursor=bad", "?dependency_limit=101", "?dependency_limit=-1", "?dependency_limit=0", "?page_size=1e1", "?page_size=1.5", "?page_size=", "?dependency_limit=bad"]) assert.equal((await app.request(path + query)).status, 400);
  assert.deepEqual(await list(), after);
  const removed = await app.request(path + "/" + created.secret_id, { method: "DELETE" });
  assert.equal(removed.status, 204);
  assert.equal(await removed.text(), "");
  for (const method of ["GET", "PATCH", "DELETE"]) assert.equal((method === "PATCH" ? await send(method, { type: "update", name: "x", value: "x" }, "/missing") : await app.request(path + "/missing", { method })).status, 404);
  assert.deepEqual(await list(), baseline);
  assert.deepEqual(await (await second.request(path)).json(), baseline);
  await app.scenario("emptySecrets");
  assert.deepEqual((await list()).secrets, []);
  assert.equal((await (await send("POST", input)).json()).secret_id, created.secret_id);
  await app.scenario("reset");
  assert.deepEqual(await list(), baseline);
  assert.equal((await (await send("POST", input)).json()).secret_id, created.secret_id);
});
test("secret scenarios dependency copies pagination and canonical variable delete guard", async () => {
  const runner = await createScenarioRunner();
  await runner.run(scenarios.startup);
  const context = runner.loadContext("/convai/secrets");
  context.dependencies.get("sim-secret")!.tools.push({ type: "unknown", id: "sim-tool-second" });
  assert.equal(context.listSecrets({ dependency_limit: 1 }).value!.secrets[0].used_by.tools_has_more, true);
  const deps = context.getDependencies("sim-secret", "tools", { page_size: 1 }).value!;
  assert.equal(deps.next_cursor, "1");
  assert.deepEqual(context.getDependencies("sim-secret", "tools", { page_size: 1, cursor: "1" }).value, { dependencies: [{ type: "unknown", id: "sim-tool-second" }], next_cursor: null });
  const configured = context.dependencies.get("sim-secret")!;
  configured.agents = [{ type: "unknown", id: "sim-agent-reference", referenced_resource_ids: ["sim-tool-reference"] }];
  configured.phone_numbers = [{ phone_number_id: "sim-phone-reference", phone_number: "+15555550100", label: "Synthetic", provider: "twilio" }];
  assert.deepEqual(context.getDependencies("sim-secret", "agents").value!.dependencies, configured.agents);
  assert.deepEqual(context.getDependencies("sim-secret", "phone_numbers").value!.dependencies, configured.phone_numbers);
  for (const bad of [{ page_size: 0 }, { page_size: 101 }, { cursor: "bad" }]) assert.equal(context.getDependencies("sim-secret", "tools", bad).error, "invalid_secret_query");
  (deps.dependencies[0] as { id: string }).id = "mutation";
  assert.equal((context.getDependencies("sim-secret", "tools").value!.dependencies[0] as { id: string }).id, "sim-tool-reference");
  assert.equal(context.deleteSecret("sim-secret"), "secret_in_use");
  assert.equal(context.getDependencies("missing", "tools").error, "secret_not_found");
  assert.equal(context.getDependencies("sim-secret", "environment_variables").error, "invalid_secret_query");
  context.dependencies.clear();
  runner.loadContext("/convai/environment-variables").createVariable({ type: "secret", label: "reference", values: { production: { secret_id: "sim-secret" } } });
  assert.equal(context.deleteSecret("sim-secret"), "secret_in_use");
  await runner.run(scenarios.emptyEnvironmentVariables);
  assert.equal(context.deleteSecret("sim-secret"), undefined);
  await runner.run(scenarios.reset);
  assert.equal(context.getDependencies("sim-secret", "tools").value!.dependencies.length, 1);
});
test("secret Dispatcher dependency previews unsupported types and missing secrets", async () => {
  const app = await createDispatcherHarness();
  const response = await app.request(path + "/sim-secret/dependencies/tools?page_size=1");
  assert.equal(response.status, 200);
  assert.deepEqual(await response.json(), { dependencies: [{ type: "unknown", id: "sim-tool-reference" }], next_cursor: null });
  for (const type of ["agents", "phone_numbers"]) {
    const result = await app.request(path + "/sim-secret/dependencies/" + type);
    assert.equal(result.status, 200);
    assert.deepEqual(await result.json(), { dependencies: [], next_cursor: null });
  }
  assert.equal((await app.request(path + "/sim-secret", { method: "DELETE" })).status, 409);
  assert.equal((await app.request(path + "/missing/dependencies/tools")).status, 404);
  for (const suffix of ["tools?page_size=0", "tools?cursor=bad", "unsupported"]) assert.equal((await app.request(path + "/sim-secret/dependencies/" + suffix)).status, 400);
  const preview = await (await app.request(path + "?dependency_limit=1")).json();
  assert.deepEqual(preview.secrets[0].used_by.tools, [{ type: "unknown", id: "sim-tool-reference" }]);
  assert.equal(preview.secrets[0].used_by.tools_has_more, false);
});
