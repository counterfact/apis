import assert from "node:assert/strict";
import test from "node:test";
import { Context } from "../api/routes/convai/tools/_.context.js";
import { createScenarioRunner } from "../test-support/scenarios.js";
import * as scenarios from "../api/scenarios/index.js";

test("tools start empty; scenarios own fixtures, copies, live dependencies, reset and isolation", async () => {
  const empty = new Context();
  assert.equal(empty.tools.size, 0);
  assert.deepEqual(empty.executions, []);
  const r = await createScenarioRunner();
  await r.run(scenarios.startup);
  const c = r.loadContext("/convai/tools");
  const baseline = c.getTool("sim-tool")!;
  baseline.tool_config.name = "external";
  assert.equal(c.getTool("sim-tool")!.tool_config.name, "display_help");
  const page = c.listTools().value!;
  page.tools[0].tool_config.description = "external";
  assert.notEqual(c.getTool("sim-tool")!.tool_config.description, "external");
  assert.equal(c.listExecutions("sim-tool").value!.executions.length, 2);
  c.listExecutions("sim-tool").value!.executions[0].request_payload = "external";
  assert.notEqual(c.listExecutions("sim-tool").value!.executions[0].request_payload, "external");
  await r.run(scenarios.toolDiscovery);
  const agents = r.loadContext("/convai/agents");
  assert.equal(c.listDependents("sim-tool").value!.agents[0].id, "sim-agent");
  const id = agents.duplicateAgent("sim-agent", {}).value!.agent_id;
  assert.equal(c.listDependents("sim-tool").value!.agents.length, 2);
  assert.equal(c.deleteTool("sim-tool").error, "tool_in_use");
  agents.deleteAgent("sim-agent");
  assert.equal(c.listDependents("sim-tool").value!.agents[0].id, id);
  await r.run(scenarios.emptyAgents);
  assert.deepEqual(c.listDependents("sim-tool").value!.agents, []);
  assert.equal(c.deleteTool("sim-tool").value, null);
  assert.equal(c.getTool("sim-tool"), undefined);
  assert.equal(c.executions.length, 0);
  await r.run(scenarios.reset);
  assert.equal(c.tools.size, 1);
  assert.equal(c.executions.length, 2);
  assert.deepEqual(c.listDependents("sim-tool").value!.agents, []);
  const other = await createScenarioRunner();
  await other.run(scenarios.startup);
  await r.run(scenarios.emptyTools);
  assert.equal(c.tools.size, 0);
  assert.equal(c.executions.length, 0);
  assert.equal(other.loadContext("/convai/tools").tools.size, 1);
  await r.run(scenarios.reset);
  assert.equal(c.getTool("sim-tool")!.tool_config.name, "display_help");
});

test("tool queries filter before deterministic pagination and invalid reads/deletes never mutate", async () => {
  const r = await createScenarioRunner();
  await r.run(scenarios.startup);
  await r.run(scenarios.toolDiscovery);
  const c = r.loadContext("/convai/tools");
  assert.equal(c.listTools({ search: "display", types: ["client"], used_by_agent_id: "sim-agent" }).value!.tools.length, 1);
  assert.deepEqual(c.listTools({ types: ["webhook"] }).value!.tools, []);
  assert.deepEqual(c.listTools({ created_by_user_id: "other", show_only_owned_documents: true }).value!.tools, []);
  assert.equal(c.listTools({ created_by_user_id: "@me" }).value!.tools.length, 2);
  assert.deepEqual(c.listTools({ used_by_agent_id: "missing" }).value!.tools, []);
  const first = c.listTools({ page_size: 1, sort_by: "name", sort_direction: "asc" }).value!;
  assert.equal(first.tools[0].id, "sim-tool");
  assert.equal(first.next_cursor, "1");
  assert.equal(c.listTools({ page_size: 1, sort_by: "name", sort_direction: "asc", cursor: "1" }).value!.has_more, false);
  assert.deepEqual(c.listTools({ cursor: "99" }).value!.tools, []);
  assert.equal(c.listExecutions("sim-tool", { is_error: true, agent_id: "sim-agent", start_time: 1735689601, end_time: 1735689601 }).value!.executions[0].id, "sim-execution-2");
  assert.equal(c.listExecutions("sim-tool", { branch_id: "missing" }).value!.executions.length, 0);
  const executions = c.listExecutions("sim-tool", { page_size: 1 }).value!;
  assert.equal(executions.executions[0].id, "sim-execution-2");
  assert.equal(c.listExecutions("sim-tool", { cursor: executions.next_cursor! }).value!.executions[0].id, "sim-execution-1");
  assert.equal(c.listDependents("sim-tool", { page_size: 1 }).value!.has_more, false);
  const before = structuredClone([...c.tools]);
  for (const q of [{ page_size: 0 }, { page_size: 101 }, { page_size: 1.5 }, { cursor: "01" }, { cursor: "-1" }, { sort_by: "bad" }, { sort_direction: "bad" }, { types: ["system"] }, { unknown: true }]) assert.equal(c.listTools(q as never).error, "invalid_tool_query");
  for (const q of [{ is_error: "false" }, { start_time: "bad" }, { start_time: 2, end_time: 1 }, { page_size: 0 }, { cursor: "bad" }, { unknown: true }]) assert.equal(c.listExecutions("sim-tool", q as never).error, "invalid_tool_query");
  assert.equal(c.listDependents("sim-tool", { page_size: 101 }).error, "invalid_tool_query");
  assert.equal(c.deleteTool("sim-tool", true).error, "unsupported_tool_force");
  assert.equal(c.getTool("missing"), undefined);
  for (const result of [c.deleteTool("missing"), c.listDependents("missing"), c.listExecutions("missing")]) assert.equal(result.error, "tool_not_found");
  assert.deepEqual([...c.tools], before);
});
