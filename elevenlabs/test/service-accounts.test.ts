import assert from "node:assert/strict";
import test from "node:test";
import { createDispatcherHarness } from "../test-support/dispatcher.js";
import { createScenarioRunner } from "../test-support/scenarios.js";
import * as scenarios from "../api/scenarios/index.js";
const path = "/v1/service-accounts";
const accountId = "sim-service-account";
const createKey = { name: "Synthetic client", permissions: ["voices_read"], character_limit: 1000, allowed_ips: ["192.0.2.1"], tts_concurrency_limit: 2 };

test("service account Dispatcher persists account and key lifecycle and isolates instances", async () => {
  const app = await createDispatcherHarness();
  const second = await createDispatcherHarness();
  const send = (suffix: string, method: string, body?: unknown) => app.request(path + suffix, { method, ...(body === undefined ? {} : { headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) }) });
  const list = async () => { const response = await send("", "GET"); assert.equal(response.status, 200); return response.json(); };
  const keys = async (id = accountId) => { const response = await send(`/${id}/api-keys`, "GET"); assert.equal(response.status, 200); return (await response.json())["api-keys"]; };
  const baseline = await list();
  assert.equal(baseline["service-accounts"][0].service_account_user_id, accountId);
  const createdAccount = await send("", "POST", { name: "Synthetic worker", default_sharing_groups: [{ group_id: "sim-group-team", permission_level: "viewer" }] });
  assert.equal(createdAccount.status, 200);
  const id = (await createdAccount.json())["service-account-user-id"];
  assert.equal(id, "sim-service-account-created-1");
  const listed = (await list())["service-accounts"].at(-1);
  assert.equal(listed.default_sharing_groups[0].group.id, "sim-group-team");
  assert.equal(listed.default_sharing_groups[0].permission_level, "viewer");
  assert.deepEqual(listed["api-keys"], []);
  const membership = await app.request("/v1/workspace/groups/sim-group-team/members", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ email: "assistant@example.invalid" }) });
  assert.equal(membership.status, 200);
  assert.equal((await list())["service-accounts"].at(-1).default_sharing_groups[0].group.members.length, 2);
  const response = await send(`/${id}/api-keys`, "POST", createKey);
  assert.equal(response.status, 200);
  const created = await response.json();
  assert.equal(created.key_id, "sim-service-key-created-1");
  assert.match(created["xi-api-key"], /^sim-not-a-real-key-/);
  const suffix = `/${id}/api-keys/${created.key_id}`;
  let stored = (await keys(id))[0];
  assert.equal(stored.name, createKey.name);
  assert.equal(stored.character_limit, 1000);
  assert.deepEqual(stored.allowed_ips, ["192.0.2.1/32"]);
  assert.equal(stored.platform_limits.concurrency.limit, 2);
  assert.equal(stored["xi-api-key"], undefined);
  assert.equal(JSON.stringify(await list()).includes(created["xi-api-key"]), false);
  const patch = { name: "Updated", permissions: "all", is_enabled: false, character_limit: "clear", allowed_ips: "clear", tts_concurrency_limit: "clear", third_party_disable_allowed: false };
  assert.equal((await send(suffix, "PATCH", patch)).status, 200);
  stored = (await keys(id))[0];
  assert.equal(stored.name, "Updated");
  assert.equal(stored.permissions, null);
  assert.equal(stored.is_disabled, true);
  assert.equal(stored.character_limit, null);
  assert.equal(stored.allowed_ips, null);
  assert.equal(stored.platform_limits.concurrency.limit, null);
  assert.equal(stored.third_party_disable_allowed, false);
  const unchanged = structuredClone(stored);
  assert.equal((await send(suffix, "PATCH")).status, 200);
  assert.equal((await send(suffix, "PATCH", {})).status, 200);
  assert.deepEqual((await keys(id))[0], unchanged);
  assert.equal((await send(suffix, "PATCH", { name: null, permissions: "no_update", character_limit: "no_update", is_enabled: "no_update" })).status, 200);
  assert.deepEqual((await keys(id))[0], unchanged);
  assert.equal((await send(suffix, "PATCH", { is_enabled: true, third_party_disable_allowed: "clear" })).status, 200);
  assert.equal((await keys(id))[0].is_disabled, false);
  assert.equal((await keys(id))[0].third_party_disable_allowed, true);
  for (let i = 0; i < 2; i++) assert.equal((await send(suffix + "/disable", "POST")).status, 200);
  assert.equal((await keys(id))[0].is_disabled, true);
  assert.equal((await keys(id))[0].disable_reason, "self_disabled");
  assert.deepEqual((await list())["service-accounts"].at(-1)["api-keys"], await keys(id));
  assert.equal((await send(suffix, "DELETE")).status, 200);
  assert.deepEqual(await keys(id), []);
  assert.equal((await send(suffix, "DELETE")).status, 404);
  for (const [suffix, method, body] of [["/missing/api-keys", "GET", undefined], ["/missing/api-keys", "POST", createKey], [`/${id}/api-keys/missing`, "PATCH", {}], [`/${id}/api-keys/missing/disable`, "POST", undefined], [`/${accountId}/api-keys/${created.key_id}`, "DELETE", undefined]] as const) assert.equal((await send(suffix, method, body)).status, 404);
  assert.deepEqual(await (await second.request(path)).json(), baseline);
  await app.scenario("emptyServiceAccounts");
  assert.deepEqual(await list(), { "service-accounts": [] });
  await app.scenario("reset");
  assert.deepEqual(await list(), baseline);
  assert.equal((await (await send("", "POST", { name: "Reset worker" })).json())["service-account-user-id"], id);
});

test("service account Dispatcher rejects invalid input atomically and applies account limit", async () => {
  const app = await createDispatcherHarness();
  const send = (suffix: string, method: string, body: unknown) => app.request(path + suffix, { method, headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) });
  const list = async () => (await app.request(path)).json();
  const baseline = await list();
  for (const body of [{}, { name: " " }, { name: "Worker", extra: true }, { name: "Worker", default_sharing_groups: [{ group_id: "missing", permission_level: "viewer" }] }, { name: "Worker", default_sharing_groups: [{ group_id: "sim-group-team", permission_level: "owner" }] }]) assert.equal((await send("", "POST", body)).status, 400);
  for (const body of [{}, { ...createKey, character_limit: -1 }, { ...createKey, allowed_ips: ["not-an-ip"] }, { ...createKey, permissions: ["unknown"] }, { ...createKey, tts_concurrency_limit: -1 }, { ...createKey, expires_at_unix: 1 }]) assert.equal((await send(`/${accountId}/api-keys`, "POST", body)).status, 400);
  for (const body of [{ name: "Wrong", character_limit: -1 }, { name: "Wrong", allowed_ips: ["invalid"] }, { name: "Wrong", expires_at_unix: 1 }, { extra: true }]) assert.equal((await send(`/${accountId}/api-keys/sim-service-key`, "PATCH", body)).status, 400);
  assert.deepEqual(await list(), baseline);
  for (let i = 1; i < 20; i++) assert.equal((await send("", "POST", { name: `Worker ${i}` })).status, 200);
  assert.equal((await send("", "POST", { name: "Over limit" })).status, 409);
  assert.equal((await list())["service-accounts"].length, 20);
});

test("service account Context keeps input and response copies isolated and scenarios replace state", async () => {
  const { Context } = await import("../api/routes/service-accounts/_.context.js");
  const context = new Context();
  assert.deepEqual(context.listAccounts(), { "service-accounts": [] });
  const id = context.createAccount({ name: "Worker" })["service-account-user-id"];
  const input = structuredClone(createKey);
  const created = context.createKey(id, input);
  input.permissions.push("voices_write");
  const key = context.listKeys(id)["api-keys"][0];
  assert.deepEqual(key.permissions, ["voices_read"]);
  key.permissions!.push("voices_write");
  assert.deepEqual(context.listKeys(id)["api-keys"][0].permissions, ["voices_read"]);
  assert.throws(() => context.updateKey(id, created.key_id, { name: "bad", character_limit: -1 }));
  assert.equal(context.listKeys(id)["api-keys"][0].name, createKey.name);
  context.updateKey(id, created.key_id, { character_limit: 0, music_concurrency_limit: 0, expires_at_unix: context.nowUnix + 900 });
  assert.equal(context.listKeys(id)["api-keys"][0].character_limit, 0);
  context.updateKey(id, created.key_id, { permissions: [], allowed_ips: ["2001:db8::1", "198.51.100.0/24"], dubbing_concurrency_limit: 3, music_concurrency_limit: 4 });
  let metadata = context.listKeys(id)["api-keys"][0];
  assert.deepEqual(metadata.permissions, []);
  assert.deepEqual(metadata.allowed_ips, ["2001:db8::1/128", "198.51.100.0/24"]);
  assert.equal(metadata.platform_limits!.dubbing_concurrency!.limit, 3);
  assert.equal(metadata.platform_limits!.music_concurrency!.limit, 4);
  const beforeInvalid = context.listKeys(id);
  for (const body of [{ permissions: ["invalid"] }, { allowed_ips: ["192.0.2.1/33"] }, { allowed_ips: ["2001:db8::1/129"] }, { allowed_ips: [] }, { expires_at_unix: context.nowUnix + 899 }, { expires_at_unix: context.nowUnix + 90 * 86_400 + 1 }, { is_enabled: null }, { third_party_disable_allowed: null }, { name: "" }, { unknown: true }]) {
    assert.throws(() => context.updateKey(id, created.key_id, body));
    assert.deepEqual(context.listKeys(id), beforeInvalid);
  }
  context.updateKey(id, created.key_id, { expires_at_unix: context.nowUnix + 90 * 86_400, character_limit: null, tts_concurrency_limit: null });
  assert.equal(context.listKeys(id)["api-keys"][0].character_limit, 0);
  context.updateKey(id, created.key_id, { expires_at_unix: "clear", dubbing_concurrency_limit: "clear", music_concurrency_limit: "clear" });
  metadata = context.listKeys(id)["api-keys"][0];
  assert.equal(metadata.expires_at_unix, null);
  assert.equal(metadata.platform_limits!.dubbing_concurrency!.limit, null);
  assert.equal(metadata.platform_limits!.music_concurrency!.limit, null);
  context.disableKey(id, created.key_id);
  context.deleteKey(id, created.key_id);
  assert.deepEqual(context.listKeys(id), { "api-keys": [] });
  assert.throws(() => context.listKeys("missing"));
  const runner = await createScenarioRunner();
  await runner.run(scenarios.startup);
  const seeded = runner.loadContext("/service-accounts");
  const baseline = seeded.listAccounts();
  seeded.createAccount({ name: "Added" });
  await runner.run(scenarios.emptyServiceAccounts);
  assert.deepEqual(seeded.listAccounts(), { "service-accounts": [] });
  await runner.run(scenarios.reset);
  assert.deepEqual(seeded.listAccounts(), baseline);
  assert.equal(seeded.createAccount({ name: "Reset" })["service-account-user-id"], "sim-service-account-created-1");
});
