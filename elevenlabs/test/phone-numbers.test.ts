import assert from "node:assert/strict";
import test from "node:test";
import { createDispatcherHarness } from "../test-support/dispatcher.js";
const path = "/v1/convai/phone-numbers";
const pagePath = "/v1/convai/v2/phone-numbers";
const twilio = { phone_number: "+15005550123", label: "New Support", provider: "twilio", sid: "AC-synthetic", token: "synthetic-only" };

test("phone Dispatcher lifecycle shares filtered and paginated state and isolates instances", async () => {
  const app = await createDispatcherHarness();
  const second = await createDispatcherHarness();
  const send = (url: string, method: string, body?: unknown) => app.request(url, { method, ...(body === undefined ? {} : { headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) }) });
  const read = async (url: string) => { const r = await app.request(url); assert.equal(r.status, 200, await r.clone().text()); assert.match(r.headers.get("content-type")!, /application\/json/); return r.json(); };
  const baseline = await read(path);
  assert.deepEqual(baseline.map((p: {phone_number_id: string}) => p.phone_number_id), ["sim-phone-twilio", "sim-phone-sip"]);
  const created = await send(path, "POST", twilio);
  assert.equal(created.status, 200);
  const id = (await created.json()).phone_number_id;
  assert.equal(id, "sim-phone-created-1");
  assert.equal((await read(`${path}/${id}`)).label, twilio.label);
  assert.doesNotMatch(JSON.stringify(await read(`${path}/${id}`)), /synthetic-only|AC-synthetic/);
  assert.equal((await read(`${path}?provider=twilio`)).length, 2);
  const assigned = await send(`${path}/${id}`, "PATCH", { agent_id: "sim-agent", label: "Z Support", environment: "production", branch_id: "sim-branch" });
  assert.equal(assigned.status, 200, await assigned.clone().text());
  const value = await assigned.json();
  assert.equal(value.assigned_agent.agent_id, "sim-agent");
  assert.equal(value.assigned_agent.branch_id, "sim-branch");
  assert.equal((await read(`${path}?agent_id=sim-agent&branch_id=sim-branch`)).length, 1);
  assert.equal((await read(`${pagePath}?label=SUPPORT&provider=twilio&supports_outbound=true`)).phone_numbers.length, 2);
  const page = await read(`${pagePath}?page_size=1&sort_by=label&sort_direction=asc`);
  assert.equal(page.phone_numbers.length, 1); assert.equal(page.has_more, true); assert.equal(page.next_cursor, "1");
  assert.equal((await read(`${pagePath}?page_size=1&cursor=2`)).has_more, false);
  assert.deepEqual((await read(`${pagePath}?cursor=99`)).phone_numbers, []);
  assert.equal((await read(`${pagePath}?search=${id}`)).phone_numbers[0].phone_number_id, id);
  assert.deepEqual((await read(`${pagePath}?search=sim-phone-created`)).phone_numbers, []);
  assert.equal((await read(`${pagePath}?phone_number=15005550123`)).phone_numbers.length, 1);
  const detached = await send(`${path}/${id}`, "PATCH", { agent_id: null });
  assert.equal(detached.status, 200); assert.equal((await detached.json()).assigned_agent, null);
  assert.equal((await send(`${path}/${id}`, "DELETE")).status, 200);
  assert.equal((await app.request(`${path}/${id}`)).status, 404);
  assert.equal((await read(path)).length, 2);
  assert.equal((await (await second.request(path)).json()).length, 2);
  await app.scenario("emptyPhoneNumbers");
  assert.deepEqual(await read(path), []); assert.deepEqual((await read(pagePath)).phone_numbers, []);
  await app.scenario("reset");
  assert.deepEqual(await read(path), baseline);
  assert.equal((await (await send(path, "POST", twilio)).json()).phone_number_id, id);
});

test("phone Dispatcher imports all provider families, projects SIP config and pages fixture logs", async () => {
  const app = await createDispatcherHarness();
  const send = (url: string, method: string, body: unknown) => app.request(url, { method, headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) });
  const sip = { phone_number: "+15005550124", label: "SIP Test", provider: "sip_trunk", inbound_trunk_config: { allowed_addresses: ["192.0.2.0/24"], credentials: { username: "synthetic-user", password: "synthetic-pass" } }, outbound_trunk_config: { address: "sip.example.invalid", transport: "tls", enabled_codecs: ["PCMU/8000"], credentials: { username: "synthetic-user", password: "synthetic-pass" } } };
  const r = await send(path, "POST", sip); assert.equal(r.status, 200, await r.clone().text());
  const id = (await r.json()).phone_number_id;
  const detail = await app.request(`${path}/${id}`); assert.equal(detail.status, 200);
  const value = await detail.json();
  assert.equal(value.provider, "sip_trunk"); assert.equal(value.livekit_stack, "standard"); assert.equal(value.outbound_trunk.has_auth_credentials, true);
  assert.deepEqual(value.inbound_trunk.allowed_addresses, ["192.0.2.0/24"]); assert.doesNotMatch(JSON.stringify(value), /synthetic-pass|"password"/);
  const updated = await send(`${path}/${id}`, "PATCH", { outbound_trunk_config: { address: "changed.example.invalid", credentials: { username: "renamed" } }, livekit_stack: "static", store_sip_messages: false });
  assert.equal(updated.status, 200); const changed = await updated.json(); assert.equal(changed.outbound_trunk.has_auth_credentials, true); assert.equal(changed.outbound_trunk.username, "renamed"); assert.equal(changed.livekit_stack, "static");
  const unchanged = await send(`${path}/${id}`, "PATCH", { label: null, livekit_stack: null, store_sip_messages: null });
  assert.equal(unchanged.status, 200); assert.deepEqual(await unchanged.json(), changed);
  const cleared = await send(`${path}/${id}`, "PATCH", { inbound_trunk_config: null, outbound_trunk_config: null });
  assert.equal(cleared.status, 200); const clearedValue = await cleared.json();
  assert.equal(clearedValue.inbound_trunk, null); assert.equal(clearedValue.outbound_trunk, null); assert.equal(clearedValue.provider_config, null);
  const again = await send(`${path}/${id}`, "PATCH", { inbound_trunk_config: null, outbound_trunk_config: null });
  assert.deepEqual(await again.json(), clearedValue);
  const exotel = await send(path, "POST", { phone_number: "+15005550125", label: "Exotel Test", provider: "exotel", account_sid: "synthetic-account", api_key: "synthetic-key", api_token: "synthetic-token", api_subdomain: "api.in.exotel.com", app_id: "synthetic-app" });
  assert.equal(exotel.status, 200); const exotelId = (await exotel.json()).phone_number_id;
  assert.equal((await (await app.request(`${path}/${exotelId}`)).json()).provider, "exotel");
  const logs = await app.request(`${path}/sim-phone-sip/sip-messages?page_size=1`); assert.equal(logs.status, 200); const first = await logs.json();
  assert.equal(first.sip_messages.length, 1); assert.equal(first.has_more, true); assert.equal(first.next_cursor, "1");
  const tail = await (await app.request(`${path}/sim-phone-sip/sip-messages?page_size=1&cursor=1`)).json(); assert.equal(tail.has_more, false); assert.equal(tail.sip_messages[0].direction, "in");
  assert.deepEqual((await (await app.request(`${path}/${id}/sip-messages`)).json()).sip_messages, []);
  assert.equal((await app.request(`${path}/missing/sip-messages`)).status, 404);
});

test("phone Dispatcher errors leave state unchanged and live agent deletion clears projection", async () => {
  const app = await createDispatcherHarness();
  const send = (url: string, method: string, body?: unknown) => app.request(url, { method, ...(body === undefined ? {} : { headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) }) });
  const baseline = await (await app.request(path)).json();
  for (const body of [{}, { ...twilio, phone_number: "bad" }, { ...twilio, extra: true }, { ...twilio, token: "" }]) assert.equal((await send(path, "POST", body)).status, 400);
  assert.equal((await send(path, "POST", { ...twilio, phone_number: baseline[0].phone_number })).status, 409);
  for (const body of [{ agent_id: "missing" }, { label: "" }, { livekit_stack: "static" }, { label: "changed", extra: true }, { branch_id: "b" }]) assert.equal((await send(`${path}/sim-phone-twilio`, "PATCH", body)).status, 400);
  for (const query of ["page_size=0", "cursor=-1", "supports_outbound=maybe", "sort_direction=invalid"]) assert.equal((await app.request(`${pagePath}?${query}`)).status, 400);
  assert.equal((await app.request(`${path}/sim-phone-sip/sip-messages?page_size=21`)).status, 400);
  assert.deepEqual(await (await app.request(path)).json(), baseline);
  assert.equal((await send(`${path}/sim-phone-twilio`, "PATCH", {agent_id:"sim-agent"})).status, 200);
  assert.equal((await send("/v1/convai/agents/sim-agent", "DELETE")).status, 204);
  assert.equal((await (await app.request(`${path}/sim-phone-twilio`)).json()).assigned_agent, null);
  assert.deepEqual(await (await app.request(`${path}?agent_id=sim-agent`)).json(), []);
});

test("phone Context owns empty state, validates atomically, copies and resets through scenarios", async () => {
  const { Context } = await import("../api/routes/convai/phone-numbers/_.context.js");
  const { createScenarioRunner } = await import("../test-support/scenarios.js");
  const scenarios = await import("../api/scenarios/index.js");
  const empty = new Context(); assert.equal(empty.phones.size, 0); assert.equal(empty.sipMessages.size, 0); assert.equal(empty.nextPhoneNumber, 0);
  const runner = await createScenarioRunner(); await runner.run(scenarios.startup);
  const context = runner.loadContext("/convai/phone-numbers");
  const baseline = context.listPhones();
  baseline[0].label = "external"; assert.notEqual(context.listPhones()[0].label, "external");
  const id = context.createPhone(twilio).phone_number_id;
  context.updatePhone(id, { agent_id: "sim-agent", branch_id: "sim-branch" });
  assert.equal(context.getPhone(id).assigned_agent?.agent_id, "sim-agent");
  const before = context.getPhone(id); const counter = context.nextPhoneNumber;
  for (const input of [null, [], { label: "changed", store_sip_messages: true }, { label: "changed", agent_id: "missing" }]) {
    assert.throws(() => context.updatePhone(id, input)); assert.deepEqual(context.getPhone(id), before);
  }
  assert.throws(() => context.createPhone({ ...twilio, phone_number: "+15005550126", provider: "sip_trunk", outbound_trunk_config: { address: 3 } }));
  assert.equal(context.nextPhoneNumber, counter);
  const sip = context.getPhone("sim-phone-sip"); if (sip.provider === "sip_trunk") sip.inbound_trunk!.allowed_addresses.push("external");
  const original = context.getPhone("sim-phone-sip"); assert.equal(original.provider, "sip_trunk"); if (original.provider === "sip_trunk") assert.deepEqual(original.inbound_trunk!.allowed_addresses, ["192.0.2.0/24"]);
  context.listSipMessages("sim-phone-sip").sip_messages[0].raw_message = "external";
  assert.notEqual(context.listSipMessages("sim-phone-sip").sip_messages[0].raw_message, "external");
  assert.equal(context.listPhonePage({supports_outbound:false}).phone_numbers.length, 1);
  assert.equal(context.listPhonePage({sort_by:"phone_number",sort_direction:"desc",page_size:1}).phone_numbers[0].phone_number_id, id);
  for(const query of [{cursor:"bad"},{page_size:0},{supports_outbound:"wrong"},{sort_by:"wrong"}]) assert.throws(() => context.listPhonePage(query as never));
  context.deletePhone("sim-phone-sip"); assert.equal(context.sipMessages.has("sim-phone-sip"), false);
  await runner.run(scenarios.emptyPhoneNumbers); assert.deepEqual(context.listPhones(), []);
  assert.deepEqual(runner.loadContext("/convai/v2").listPhoneNumbers({}).phone_numbers, []);
  await runner.run(scenarios.reset); assert.equal(context.phones.size, 2); assert.equal(context.nextPhoneNumber, 0); assert.equal(context.listSipMessages("sim-phone-sip").sip_messages.length, 2);
});
