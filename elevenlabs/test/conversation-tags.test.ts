const path = "/v1/convai/tags";

test("tag context owns CRUD, pagination and defensive copies", () => {
  const context = new Context();
  assert.deepEqual(context.listTags(), { value: { conversation_tags: [], next_cursor: null, has_more: false } });
  context.creationTimeUnix = 1735689600;
  context.workspaceId = "sim-workspace";
  context.ownerUserId = "sim-user";
  const first = context.createTag({ title: "Same", description: "original" }).value!;
  assert.deepEqual(first, { tag_id: "sim-tag-created-1", title: "Same", description: "original", workspace_id: "sim-workspace", owner_user_id: "sim-user", created_at_unix_secs: 1735689601 });
  first.title = "external";
  const second = context.createTag({ title: "Same" }).value!;
  assert.equal(second.tag_id, "sim-tag-created-2");
  assert.equal(second.description, null);
  const page = context.listTags({ page_size: 1 }).value!;
  assert.deepEqual(page, { conversation_tags: [second], next_cursor: "1", has_more: true });
  page.conversation_tags[0].title = "external";
  assert.equal(context.getTag(second.tag_id)!.title, "Same");
  const read = context.getTag(second.tag_id)!;
  read.description = "external";
  assert.equal(context.getTag(second.tag_id)!.description, null);
  assert.deepEqual(context.listTags({ cursor: "1" }).value!.conversation_tags.map(tag => tag.tag_id), [first.tag_id]);
  assert.deepEqual(context.listTags({ cursor: "100" }).value, { conversation_tags: [], next_cursor: null, has_more: false });
  for (const cursor of ["", "-1", "1.5", "abc", "9007199254740992"]) assert.equal(context.listTags({ cursor }).error, "invalid_tag_query");
  for (const page_size of [0, 101, 1.5, NaN]) assert.equal(context.listTags({ page_size }).error, "invalid_tag_query");
  assert.equal(context.updateTag(first.tag_id, { title: null }).value!.description, "original");
  assert.equal(context.updateTag(first.tag_id, { description: null }).value!.description, null);
  assert.equal(context.updateTag(first.tag_id, { description: "" }).value!.description, "");
  assert.equal(context.updateTag(first.tag_id, { title: "Same" }).value!.title, "Same");
  const updated = context.updateTag(first.tag_id, {}).value!;
  updated.title = "external";
  assert.equal(context.getTag(first.tag_id)!.title, "Same");
  const before = context.listTags();
  assert.equal(context.createTag({ title: "" }).error, "invalid_tag");
  assert.equal(context.updateTag(first.tag_id, { title: "", description: "changed" }).error, "invalid_tag");
  assert.deepEqual(context.listTags(), before);
  assert.equal(context.createTag({ title: "Third" }).value!.tag_id, "sim-tag-created-3");
  assert.equal(context.getTag("missing"), undefined);
  assert.equal(context.updateTag("missing", {}).error, "tag_not_found");
  assert.equal(context.deleteTag("missing"), false);
  assert.equal(context.deleteTag(second.tag_id), true);
  assert.equal(context.getTag(second.tag_id), undefined);
  context.tags.set("sim-tag-created-4", { ...first, tag_id: "sim-tag-created-4" });
  assert.equal(context.createTag({ title: "After collision" }).value!.tag_id, "sim-tag-created-5");
  const tie = new Context();
  tie.tags.set("b", { ...first, tag_id: "b" });
  tie.tags.set("a", { ...first, tag_id: "a" });
  assert.deepEqual(tie.listTags().value!.conversation_tags.map(tag => tag.tag_id), ["a", "b"]);
});

test("tag scenarios restore baseline, counters and isolated contexts", async () => {
  const runner = await createScenarioRunner();
  const context = runner.loadContext("/convai/tags");
  assert.deepEqual(context.listTags().value!.conversation_tags, []);
  await runner.run(scenarios.startup);
  const baseline = context.listTags();
  assert.equal(baseline.value!.conversation_tags[0].tag_id, "sim-tag");
  context.createTag({ title: "New" });
  await runner.run(scenarios.emptyTags);
  assert.deepEqual(context.listTags().value!.conversation_tags, []);
  assert.equal(context.createTag({ title: "New" }).value!.tag_id, "sim-tag-created-1");
  await runner.run(scenarios.reset);
  assert.deepEqual(context.listTags(), baseline);
  assert.equal(context.createTag({ title: "New" }).value!.tag_id, "sim-tag-created-1");
});

test("conversation tag Dispatcher CRUD, pagination, validation, reset and isolation", async () => {
  const app = await createDispatcherHarness();
  const other = await createDispatcherHarness();
  const send = (method: string, body: unknown, suffix = "") => app.request(path + suffix, { method, headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) });
  const list = async (query = "") => {
    const response = await app.request(path + query);
    assert.equal(response.status, 200);
    assert.match(response.headers.get("content-type")!, /application\/json/);
    return response.json();
  };
  const baseline = await list();
  assert.equal(baseline.conversation_tags.length, 1);
  for (const body of [{}, { title: "" }, { title: null }, { title: 1 }, { title: "x".repeat(121) }, { title: "X", description: "x".repeat(1001) }]) assert.equal((await send("POST", body)).status, 400);
  assert.deepEqual(await list(), baseline);
  const response = await send("POST", { title: "New", description: "Original" });
  assert.equal(response.status, 200);
  const created = await response.json();
  assert.deepEqual(created, { tag_id: "sim-tag-created-1", title: "New", description: "Original", workspace_id: "sim-workspace", owner_user_id: "sim-user", created_at_unix_secs: 1735689601 });
  const duplicate = await send("POST", { title: "New" });
  assert.equal(duplicate.status, 200);
  assert.equal((await duplicate.json()).tag_id, "sim-tag-created-2");
  const page = await list("?page_size=1");
  assert.equal(page.conversation_tags[0].tag_id, "sim-tag-created-2");
  assert.equal(page.has_more, true);
  assert.equal(page.next_cursor, "1");
  assert.equal((await list("?page_size=1&cursor=1")).conversation_tags[0].tag_id, created.tag_id);
  assert.deepEqual(await list("?cursor=100"), { conversation_tags: [], next_cursor: null, has_more: false });
  for (const query of ["?page_size=0", "?page_size=101", "?page_size=1.5", "?cursor=no", "?cursor=-1", "?cursor="]) assert.equal((await app.request(path + query)).status, 400);
  const limits = await send("POST", { title: "x".repeat(120), description: "x".repeat(1000) });
  assert.equal(limits.status, 200);
  const limitsId = (await limits.json()).tag_id;
  assert.equal((await app.request(path + `/${limitsId}`, { method: "DELETE" })).status, 204);
  const suffix = `/${created.tag_id}`;
  assert.deepEqual(await (await app.request(path + suffix)).json(), created);
  const edited = await send("PATCH", { title: "Edited" }, suffix);
  assert.equal(edited.status, 200);
  assert.deepEqual(await edited.json(), { ...created, title: "Edited" });
  assert.equal((await (await send("PATCH", { title: null, description: null }, suffix)).json()).description, null);
  const after = await list();
  for (const body of [{ title: "" }, { title: "x".repeat(121) }, { title: "Bad", description: 3 }, { description: "x".repeat(1001) }]) assert.equal((await send("PATCH", body, suffix)).status, 400);
  assert.deepEqual(await list(), after);
  assert.equal((await send("PATCH", {}, suffix)).status, 200);
  assert.deepEqual(await list(), after);
  for (const method of ["GET", "PATCH", "DELETE"]) {
    const missing = method === "PATCH" ? await send(method, {}, "/missing") : await app.request(path + "/missing", { method });
    assert.equal(missing.status, 404);
    assert.equal((await missing.json()).detail.status, "tag_not_found");
  }
  assert.deepEqual(await list(), after);
  const deleted = await app.request(path + suffix, { method: "DELETE" });
  assert.equal(deleted.status, 204);
  assert.equal(await deleted.text(), "");
  assert.equal((await app.request(path + suffix)).status, 404);
  assert.equal((await app.request(path + suffix, { method: "DELETE" })).status, 404);
  assert.equal((await list()).conversation_tags.length, 2);
  assert.deepEqual(await (await other.request(path)).json(), baseline);
  await app.scenario("emptyTags");
  assert.deepEqual(await list(), { conversation_tags: [], next_cursor: null, has_more: false });
  assert.equal((await (await send("POST", { title: "New" })).json()).tag_id, "sim-tag-created-1");
  await app.scenario("reset");
  assert.deepEqual(await list(), baseline);
  assert.equal((await (await send("POST", { title: "New" })).json()).tag_id, "sim-tag-created-1");
  assert.equal((await (await app.request("/v1/voices")).json()).voices.length, 2);
});
