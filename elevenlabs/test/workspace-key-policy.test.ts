test("workspace key policy Context resolves live keys and override/default precedence",async()=>{
  const {Context}=await import("../api/routes/workspaces/api-keys/_.context.js");
  const empty=new Context();assert.equal(empty.callers.size,0);
  const runner=await createScenarioRunner();await runner.run(scenarios.startup);
  const c=runner.loadContext("/workspaces/api-keys"),service=runner.loadContext("/service-accounts");
  assert.throws(()=>c.disableSelf("self",undefined));
  assert.throws(()=>c.disableSelf("other","sim-workspace-caller"));
  service.updateKey("sim-service-account","sim-service-key",{third_party_disable_allowed:false});
  assert.throws(()=>c.disableSelf("self","sim-workspace-caller"));
  c.setPolicy({third_party_disable_allowed:true});c.disableSelf("self","sim-workspace-caller");
  assert.equal(service.listKeys("sim-service-account")["api-keys"][0].is_disabled,true);
  service.updateKey("sim-service-account","sim-service-key",{is_enabled:true});
  c.setPolicy({});assert.equal(c.override,true);
  c.setPolicy({third_party_disable_allowed:null});assert.equal(c.override,null);
  assert.throws(()=>c.disableSelf("self","sim-workspace-caller"));
  const key=service.accounts.get("sim-service-account")!.keys.get("sim-service-key")!;
  key.third_party_disable_allowed=null;c.planDefault=false;
  assert.throws(()=>c.disableSelf("self","sim-workspace-caller"));
  c.planDefault=true;c.disableSelf("self","sim-workspace-caller");
  c.setPolicy({third_party_disable_allowed:false});
  assert.throws(()=>c.disableSelf("self","sim-workspace-caller"));
  assert.throws(()=>c.setPolicy({third_party_disable_allowed:"yes"}));assert.equal(c.override,false);
  service.deleteKey("sim-service-account","sim-service-key");
  assert.throws(()=>c.disableSelf("self","sim-workspace-caller"));
  await runner.run(scenarios.reset);assert.equal(c.override,null);
  assert.equal(service.listKeys("sim-service-account")["api-keys"][0].is_disabled,false);
});
