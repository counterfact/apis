import assert from "node:assert/strict";
import test from "node:test";
import { createScenarioRunner } from "../test-support/scenarios.js";
import { createDispatcherHarness } from "../test-support/dispatcher.js";
import * as scenarios from "../api/scenarios/index.js";

const id = "sim-agent", main = "sim-main-branch", feature = "sim-agent-feature";
test("branch context plans three-way changes and commits immutable ancestry with live references", async () => {
  const r = await createScenarioRunner();
  await r.run(scenarios.startup);
  const c = r.loadContext("/convai/agents/{agent_id}/branches");
  await r.run(scenarios.agentAnalysisReferences);
  await r.run(scenarios.knowledgeBaseReferences);
  await r.run(scenarios.mcpAgentReference);
  const before = structuredClone([...c.versions]);
  const preview = c.mergePreview(id, feature, main);
  assert.equal(preview.conversation_config.agent!.first_message, "Feature greeting");
  assert.equal(preview.conversation_config.agent!.prompt!.knowledge_base![0].id, "sim-kb-text");
  assert.equal(preview.platform_settings!.analysis_items!.evaluation_criteria![0].analysis_item_id, "sim-analysis-evaluation");
  assert.deepEqual(preview.conversation_config.agent!.prompt!.mcp_server_ids, ["sim-mcp"]);
  assert.deepEqual([...c.versions], before);
  preview.conversation_config.agent!.first_message = "mutated";
  const result = c.merge(id, feature, main, { archive_source_branch: false });
  assert.equal(c.select(id, {}).conversation_config.agent!.first_message, "Feature greeting");
  const version = c.version(id, result.version_id);
  assert.equal(version.parents.in_branch_parent_id, "sim-agent-version-main");
  assert.equal(version.parents.merged_from_version_id, "sim-agent-version-feature");
  assert.equal(c.get(id, main).most_recent_versions![0].id, result.version_id);
  assert.equal(c.select(id, { version_id: "sim-agent-version-main" }).conversation_config.agent!.first_message, "Hello from the simulator.");
  assert.equal(c.select(id, {}).procedures!["sim-procedure"].version_id, "sim-procedure-version");
  assert.equal(r.loadContext("/convai/agents/{agent_id}/branches/{branch_id}/procedures").get(id, main, "sim-procedure").version_id, "sim-procedure-version");
  await r.run(scenarios.reset);
  assert.equal(c.versions.size, 2);
  assert.equal(c.select(id, {}).conversation_config.agent!.first_message, "Hello from the simulator.");
});

test("branch context resolves conflicts deterministically and fails atomically", async () => {
  const r = await createScenarioRunner(); await r.run(scenarios.startup);
  const c = r.loadContext("/convai/agents/{agent_id}/branches");
  await r.run(scenarios.branchMergeConflicts);
  const p = c.mergePreview(id, feature, main);
  assert.equal(p.conversation_config.agent!.first_message, "Main changed greeting");
  assert.deepEqual(p.overridden_fields, ["conversation_config.agent.first_message"]);
  assert.deepEqual(p.conflicts, [{ section: "conversation_config", path: "agent.first_message", base_value: "Hello from the simulator.", source_value: "Feature greeting", target_value: "Main changed greeting" }]);
  assert.equal(c.mergePreview(id, feature, main, { force: true }).conversation_config.agent!.first_message, "Feature greeting");
  assert.equal(c.rebasePreview(id, feature).conversation_config.agent!.first_message, "Feature greeting");
  const before = structuredClone({ branches: [...c.branches], versions: [...c.versions] });
  assert.throws(() => c.merge(id, main, feature, {}), { code: "branch_in_use" });
  assert.throws(() => c.merge(id, feature, main, { force: "yes" }), { status: 400 });
  assert.throws(() => c.mergePreview(id, feature, feature), { status: 400 });
  assert.throws(() => c.mergePreview(id, "missing", main), { status: 404 });
  assert.deepEqual({ branches: [...c.branches], versions: [...c.versions] }, before);
  const result = c.rebase(id, feature, undefined, {});
  assert.equal(c.version(id, result.version_id).parents.rebased_from_version_id, "sim-agent-version-main");
  assert.equal(c.select(id, { branch_id: feature }).conversation_config.agent!.language, "es");
  assert.throws(() => c.rebase(id, feature, undefined, {}), { code: "branch_already_up_to_date" });
  assert.equal(c.select(id, {}).conversation_config.agent!.first_message, "Main changed greeting");
});

test("validated Dispatcher previews and applies merges/rebases with reset and isolated state", async () => {
  const h = await createDispatcherHarness();
  const base = `/v1/convai/agents/${id}/branches`;
  const req = async (suffix: string, method = "GET", body?: unknown, status = 200) => {
    const response = await h.request(base + suffix, { method, ...(body === undefined ? {} : { headers: { "content-type": "application/json" }, body: JSON.stringify(body) }) });
    assert.equal(response.status, status, await response.clone().text());
    return response;
  };
  await h.scenario("branchMergeConflicts");
  const preview = await (await req(`/${feature}/merge-preview?target_branch_id=${main}&force=true`)).json();
  assert.equal(preview.conversation_config.agent.first_message, "Feature greeting");
  assert.equal(preview.conflicts.length, 1);
  const merged = await (await req(`/${feature}/merge?target_branch_id=${main}`, "POST", { force: true })).json();
  assert.equal((await (await h.request(`/v1/convai/agents/${id}?branch_id=${main}`)).json()).version_id, merged.version_id);
  assert.equal((await (await req(`/${feature}`)).json()).is_archived, true);
  await req(`/${feature}/rebase-preview`, "GET", undefined, 409);
  await h.scenario("reset");
  const rb = await (await req(`/${feature}/rebase-preview`)).json();
  assert.equal(rb.source_identical_to_target, true);
  await req(`/${feature}/rebase`, "POST", {}, 409);
  await h.scenario("branchMergeConflicts");
  const rebased = await (await req(`/${feature}/rebase`, "POST", {})).json();
  assert.equal((await (await req(`/${feature}`)).json()).most_recent_versions[0].id, rebased.version_id);
  await req(`/${feature}/merge-preview?target_branch_id=${main}&include_procedure_generated_workflow_elements=true`, "GET", undefined, 400);
  await req(`/${feature}/merge?target_branch_id=${feature}`, "POST", {}, 400);
  await req(`/${feature}/rebase`, "POST", { unsupported: true }, 400);
  const other = await createDispatcherHarness();
  assert.equal((await (await other.request(`/v1/convai/agents/${id}?branch_id=${main}`)).json()).version_id, "sim-agent-version-main");
  await h.scenario("reset");
  assert.equal((await (await req(`/${feature}`)).json()).most_recent_versions.length, 1);
});

test("published procedure references move as units while working drafts remain branch-local", async () => {
  const r = await createScenarioRunner(); await r.run(scenarios.startup);
  const c = r.loadContext("/convai/agents/{agent_id}/branches");
  const procedures = r.loadContext("/convai/agents/{agent_id}/branches/{branch_id}/procedures");
  await r.run(scenarios.branchMergeReferences);
  const draft = procedures.create(id, feature, { name: "Unpublished", content: "" });
  const p = c.mergePreview(id, feature, main, { force: true });
  assert.deepEqual(p.conversation_config.agent!.prompt!.tool_ids, ["feature-tool"]);
  assert.equal(p.procedures!["sim-procedure"].version_id, "sim-procedure-feature-version");
  assert.equal(p.procedures![draft.procedure_id], undefined);
  c.merge(id, feature, main, { force: true, archive_source_branch: false });
  assert.equal(procedures.get(id, main, "sim-procedure").name, "Published feature support");
  assert.throws(() => procedures.draft(id, main, draft.procedure_id), { status: 404 });
  assert.equal(procedures.draft(id, feature, draft.procedure_id).name, "Unpublished");
  assert.equal(procedures.get(id, main, "sim-procedure", { agent_version_id: "sim-agent-version-main" }).version_id, "sim-procedure-version");
  const before = c.versions.size;
  c.merge(id, feature, main, { archive_source_branch: false });
  assert.equal(c.versions.size, before + 1);
  assert.deepEqual(c.mergePreview(id, feature, main).conflicts, []);
  const other = r.loadContext("/convai/agents").duplicateAgent(id, {}).value!.agent_id;
  assert.throws(() => c.merge(other, feature, main, {}), { status: 404 });
  await r.run(scenarios.reset);
  assert.equal(c.merge(id, feature, main, { archive_source_branch: false }).version_id, "sim-agent-version-created-1");
});
