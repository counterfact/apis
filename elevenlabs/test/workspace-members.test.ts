import assert from "node:assert/strict";
import test from "node:test";
import { createDispatcherHarness } from "../test-support/dispatcher.js";
import { createScenarioRunner } from "../test-support/scenarios.js";
import * as scenarios from "../api/scenarios/index.js";

test("workspace member context shares roster, updates atomically, and tracks invitations", async () => {
  const { Context } = await import("../api/routes/workspace/_.context.js");
  const empty = new Context();
  assert.deepEqual(empty.listMembers(), []);
  assert.equal(empty.invitations.size, 0);
  const runner = await createScenarioRunner();
  await runner.run(scenarios.startup);
  const c = runner.loadContext("/workspace");
  const baseline = c.listMembers();
  assert.equal(baseline.length, 2);
  c.updateMember({email:"assistant@example.invalid",is_locked:false,workspace_seat_type:"workspace_lite_member"});
  assert.equal(c.listMembers()[0].is_locked,false);
  assert.equal(c.listMembers()[0].seat_type,"workspace_lite_member");
  const updated = c.listMembers();
  assert.throws(() => c.updateMember({email:"assistant@example.invalid",is_locked:true,workspace_seat_type:"invalid"}));
  assert.deepEqual(c.listMembers(),updated);
  c.updateMember({email:"assistant@example.invalid",is_locked:null,workspace_role:null});
  assert.deepEqual(c.listMembers(),updated);
  c.updateMember({email:"assistant@example.invalid",workspace_role:"workspace_admin",workspace_seat_type:"workspace_member",allow_downgrade_to_basic_seat:true});
  assert.equal(c.listMembers()[0].seat_type,"workspace_member");
  for (const body of [{email:"missing@example.invalid"},{email:"invalid"},{email:"assistant@example.invalid",extra:true}]) assert.throws(() => c.updateMember(body));
  const invitation = {email:"new@example.invalid",group_ids:["sim-group-team"],usage_limit:50};
  c.invite(invitation);
  invitation.group_ids.push("external mutation");
  assert.deepEqual(c.invitations.get("new@example.invalid")!.group_ids,["sim-group-team"]);
  assert.equal(c.invitations.get("new@example.invalid")!.usage_limit,50);
  assert.equal(c.listMembers().length,2);
  assert.throws(() => c.invite({email:"assistant@example.invalid"}));
  assert.throws(() => c.invite({email:"new@example.invalid",group_ids:["unknown"]}));
  assert.equal(c.invitations.get("new@example.invalid")!.usage_limit,50);
  const before = structuredClone(c.invitations);
  for (const body of [{emails:["ok@example.invalid","bad@other.invalid"]},{emails:["ok@example.invalid","assistant@example.invalid"]},{emails:[]},{emails:["ok@example.invalid"],usage_limit:-1}]) assert.throws(() => c.inviteBulk(body));
  assert.deepEqual(c.invitations,before);
  c.inviteBulk({emails:["bulk@example.invalid","bulk@example.invalid"],seat_type:"workspace_lite_member"});
  assert.equal(c.invitations.size,2);
  c.invite({email:"bulk@example.invalid",workspace_permission:"workspace_admin",seat_type:"workspace_member"});
  assert.equal(c.invitations.get("bulk@example.invalid")!.seat_type,"workspace_member");
  assert.equal(c.invitations.size,2);
  c.deleteInvite({email:"new@example.invalid"});
  assert.equal(c.invitations.has("new@example.invalid"),false);
  assert.throws(() => c.deleteInvite({email:"new@example.invalid"}));
  c.listMembers()[0].first_name="mutated";
  assert.notEqual(c.listMembers()[0].first_name,"mutated");
  await runner.run(scenarios.emptyGroups);
  assert.deepEqual(c.listMembers(),[]);
  await runner.run(scenarios.reset);
  assert.deepEqual(c.listMembers(),baseline);
  assert.equal(c.invitations.size,0);
});

test("workspace member Dispatcher edits, invite atomicity, roster consistency and reset", async () => {
  const app = await createDispatcherHarness(), second = await createDispatcherHarness();
  const base = "/v1/workspace";
  const send = (path:string, method:string, body:unknown) => app.request(base+path,{method,headers:{"Content-Type":"application/json"},body:JSON.stringify(body)});
  const read = async () => {
    const r = await app.request(base+"/members");
    assert.equal(r.status,200); assert.match(r.headers.get("content-type")!,/application\/json/);
    return r.json();
  };
  const baseline = await read(); assert.equal(baseline.length,2);
  assert.equal(baseline[0].email,"assistant@example.invalid"); assert.equal(baseline[0].is_locked,true);
  const edit = await send("/members","POST",{email:"assistant@example.invalid",is_locked:false,workspace_role:"workspace_admin"});
  assert.equal(edit.status,200); assert.deepEqual(await edit.json(),{status:"ok"});
  assert.equal((await read())[0].seat_type,"workspace_admin"); assert.equal((await read())[0].is_locked,false);
  assert.equal((await send("/members","POST",{email:"assistant@example.invalid",is_locked:true,workspace_seat_type:"bogus"})).status,400);
  assert.equal((await read())[0].is_locked,false);
  assert.equal((await send("/members","POST",{email:"missing@example.invalid"})).status,404);
  for(const body of [{},null,{email:4},{email:"bad"},{email:"assistant@example.invalid",extra:true}]) assert.equal((await send("/members","POST",body)).status,400);
  const invite = await send("/invites/add","POST",{email:"new@example.invalid",group_ids:["sim-group-team"]});
  assert.equal(invite.status,200); assert.deepEqual(await invite.json(),{status:"ok"});
  assert.equal((await read()).length,2);
  assert.equal((await send("/groups/sim-group-team/members","POST",{email:"new@example.invalid"})).status,404);
  assert.equal((await send("/invites/add","POST",{email:"assistant@example.invalid"})).status,400);
  assert.equal((await send("/invites/add","POST",{email:"other@example.invalid",group_ids:["missing"]})).status,404);
  assert.equal((await send("/invites/add-bulk","POST",{emails:["atomic@example.invalid","bad@other.invalid"]})).status,400);
  assert.equal((await send("/invites","DELETE",{email:"atomic@example.invalid"})).status,404);
  const bulk = await send("/invites/add-bulk","POST",{emails:["bulk@example.invalid","bulk@example.invalid"],seat_type:"workspace_lite_member",usage_limit:0});
  assert.equal(bulk.status,200); assert.deepEqual(await bulk.json(),{status:"ok"});
  for(const body of [{emails:[]},{emails:["bad"]},{emails:["new@example.invalid"],usage_limit:-1}]) assert.equal((await send("/invites/add-bulk","POST",body)).status,400);
  assert.equal((await send("/invites","DELETE",{email:"new@example.invalid"})).status,200);
  assert.equal((await send("/invites","DELETE",{email:"new@example.invalid"})).status,404);
  assert.equal((await send("/invites","DELETE",{email:"bulk@example.invalid"})).status,200);
  assert.deepEqual(await (await second.request(base+"/members")).json(),baseline);
  assert.equal((await send("/invites/add","POST",{email:"reset@example.invalid"})).status,200);
  await app.scenario("reset","api"); assert.deepEqual(await read(),baseline);
  assert.equal((await send("/invites","DELETE",{email:"reset@example.invalid"})).status,404);
  await app.scenario("emptyWorkspaceMembers","api"); assert.deepEqual(await read(),[]);
  const groups = await (await app.request(base+"/groups")).json(); assert.deepEqual(groups["sim-group-team"].members,[]);
  await app.scenario("reset","api"); assert.deepEqual(await read(),baseline);
});
