import assert from "node:assert/strict";
import test from "node:test";
import { createScenarioRunner } from "../test-support/scenarios.js";
import { createDispatcherHarness } from "../test-support/dispatcher.js";
import { Context } from "../api/routes/convai/agents/_.context.js";
import * as scenarios from "../api/scenarios/index.js";
const agentPath = "/v1/convai/agents/sim-agent";
const remove = { method: "DELETE" };
test("hold removal context changes only live custom metadata and is idempotent", async () => {
  assert.equal(new Context().agents.size, 0);
  const r = await createScenarioRunner();
  await r.run(scenarios.startup);
  const c = r.loadContext("/convai/agents");
  assert.equal(typeof c.deleteHoldAudio, "function");
  const initial = c.getAgent("sim-agent");
  assert.deepEqual(c.deleteHoldAudio("sim-agent"), { value: { agent_id: "sim-agent" } });
  assert.deepEqual(c.getAgent("sim-agent"), initial);
  await r.run(scenarios.agentHoldAudioFixture);
  const lifecycle = r.loadContext("/convai/agents/{agent_id}/branches");
  const history = structuredClone([...lifecycle.versions]);
  const branches = structuredClone([...lifecycle.branches]);
  const expected = c.getAgent("sim-agent")!;
  delete expected.platform_settings!.queueing_config!.hold_audio;
  assert.deepEqual(c.deleteHoldAudio("sim-agent"), { value: { agent_id: "sim-agent" } });
  assert.deepEqual(c.getAgent("sim-agent"), expected);
  assert.deepEqual(lifecycle.select("sim-agent", { branch_id: "sim-main-branch" }), expected);
  assert.deepEqual([...lifecycle.versions], history);
  assert.deepEqual([...lifecycle.branches], branches);
  c.deleteHoldAudio("sim-agent");
  assert.deepEqual(c.getAgent("sim-agent"), expected);
  const all = structuredClone([...c.agents]);
  assert.equal(c.deleteHoldAudio("missing").error, "agent_not_found");
  assert.deepEqual([...c.agents], all);
  await r.run(scenarios.reset);
  assert.deepEqual(c.getAgent("sim-agent"), initial);
  const isolated = await createScenarioRunner();
  await isolated.run(scenarios.startup);
  await isolated.run(scenarios.agentHoldAudioFixture);
  assert.ok(isolated.loadContext("/convai/agents").getAgent("sim-agent")!.platform_settings!.queueing_config!.hold_audio);
});
test("validated Dispatcher removes custom hold metadata from canonical and main reads only", async () => {
  const h = await createDispatcherHarness();
  const initial = await (await h.request(agentPath)).json();
  const noCustom = await h.request(agentPath + "/hold-audio", remove);
  assert.equal(noCustom.status, 200);
  assert.deepEqual(await noCustom.json(), { agent_id: "sim-agent" });
  assert.deepEqual(await (await h.request(agentPath)).json(), initial);
  await h.scenario("agentHoldAudioFixture");
  const before = await (await h.request(agentPath)).json();
  const historicalPath = agentPath + "?version_id=sim-agent-version-main";
  const featurePath = agentPath + "?branch_id=sim-agent-feature";
  const historical = await (await h.request(historicalPath)).json();
  const feature = await (await h.request(featurePath)).json();
  const expected = structuredClone(before);
  delete expected.platform_settings.queueing_config.hold_audio;
  const response = await h.request(agentPath + "/hold-audio", remove);
  assert.equal(response.status, 200);
  assert.match(response.headers.get("content-type")!, /application\/json/);
  assert.deepEqual(await response.json(), { agent_id: "sim-agent" });
  assert.deepEqual(await (await h.request(agentPath)).json(), expected);
  assert.deepEqual(await (await h.request(agentPath + "?branch_id=sim-main-branch")).json(), expected);
  assert.deepEqual(await (await h.request(historicalPath)).json(), historical);
  assert.deepEqual(await (await h.request(featurePath)).json(), feature);
  assert.equal((await h.request(agentPath + "/hold-audio", remove)).status, 200);
  assert.deepEqual(await (await h.request(agentPath)).json(), expected);
  const missing = await h.request(agentPath.replace("sim-agent", "missing") + "/hold-audio", remove);
  assert.equal(missing.status, 404);
  assert.equal((await missing.json()).detail.status, "agent_not_found");
  assert.deepEqual(await (await h.request(agentPath)).json(), expected);
  const isolated = await createDispatcherHarness();
  await isolated.scenario("agentHoldAudioFixture");
  assert.deepEqual(await (await isolated.request(agentPath)).json(), before);
  await h.scenario("reset");
  assert.deepEqual(await (await h.request(agentPath)).json(), initial);
  assert.equal((await h.request(agentPath, remove)).status, 204);
  assert.equal((await h.request(agentPath + "/hold-audio", remove)).status, 404);
});
