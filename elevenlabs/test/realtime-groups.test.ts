import assert from "node:assert/strict";
import test from "node:test";
import { createDispatcherHarness } from "../test-support/dispatcher.js";
import { createScenarioRunner } from "../test-support/scenarios.js";
import * as scenarios from "../api/scenarios/index.js";
const path = "/v1/convai/realtime/conversation-groups";
test("realtime context validates atomic unique edits and membership transitions", async () => {
  const { Context } = await import("../api/routes/convai/realtime/_.context.js");
  const empty = new Context();
  assert.equal(empty.groups.size,0); assert.equal(empty.conversations.size,0);
  const runner = await createScenarioRunner(); await runner.run(scenarios.startup);
  const c = runner.loadContext("/convai/realtime");
  const g = c.createGroup({title:"  Synthetic   Work ",description:"Test"});
  assert.equal(g.title,"Synthetic Work");
  assert.throws(() => c.createGroup({title:"synthetic work"}));
  const baseline = c.getGroup(g.id);
  assert.throws(() => c.updateGroup(g.id,{title:"Simulator Sessions",description:"changed"}));
  assert.deepEqual(c.getGroup(g.id),baseline);
  assert.equal(c.updateGroup(g.id,{description:null}).description,null);
  assert.equal(c.updateGroup(g.id,{title:null}).title,g.title);
  g.access_info.creator_name="changed";
  assert.notEqual(c.getGroup(g.id).access_info.creator_name,"changed");
  c.setGroup("sim-realtime-conversation",{conversation_group_id:g.id});
  assert.equal(c.conversations.get("sim-realtime-conversation"),g.id);
  assert.throws(() => c.setGroup("sim-realtime-conversation",{conversation_group_id:"missing"}));
  assert.equal(c.conversations.get("sim-realtime-conversation"),g.id);
  c.setGroup("sim-realtime-conversation",{conversation_group_id:"sim-realtime-group"});
  c.deleteGroup("sim-realtime-group");
  assert.equal(c.conversations.get("sim-realtime-conversation"),null);
  c.clearGroup("sim-realtime-conversation"); assert.throws(() => c.clearGroup("missing"));
  for(const input of [{title:" "},{title:"a".repeat(65)},{title:"valid",description:"a".repeat(501)}]) assert.throws(() => c.createGroup(input));
  for(const q of [{page_size:0},{cursor:"invalid"},{search:"a".repeat(65)}]) assert.throws(() => c.listGroups(q));
  assert.equal(c.listGroups({cursor:"999"}).conversation_groups.length,0);
  await runner.run(scenarios.reset);
  assert.equal(c.groups.size,2); assert.equal(c.nextId,1);
  assert.equal(c.conversations.get("sim-realtime-conversation"),"sim-realtime-group");
});
test("realtime Dispatcher CRUD paging validation membership isolation and reset", async () => {
  const app = await createDispatcherHarness(), second = await createDispatcherHarness();
  const send = (url:string,method:string,body?:unknown) => app.request(url,{method,...(body===undefined?{}:{headers:{"Content-Type":"application/json"},body:JSON.stringify(body)})});
  const first = await app.request(`${path}?page_size=1`); assert.equal(first.status,200);
  assert.match(first.headers.get("content-type")!,/application\/json/);
  const p = await first.json(); assert.equal(p.conversation_groups.length,1); assert.equal(p.has_more,true);
  const next = await (await app.request(`${path}?page_size=1&cursor=${p.next_cursor}`)).json();
  assert.equal(next.has_more,false); assert.notEqual(next.conversation_groups[0].id,p.conversation_groups[0].id);
  assert.equal((await (await app.request(`${path}?search=HISTORICAL`)).json()).conversation_groups.length,1);
  const created = await send(path,"POST",{title:"New Group",description:"Original"}); assert.equal(created.status,200);
  const g = await created.json();
  assert.equal((await send(path,"POST",{title:" new   GROUP "})).status,409);
  assert.equal((await send(path,"POST",{title:5})).status,400);
  assert.equal((await send(path,"POST",{title:" "})).status,400);
  assert.equal((await send(`${path}/${g.id}`,"PATCH",{description:null})).status,200);
  assert.equal((await (await app.request(`${path}/${g.id}`)).json()).description,null);
  assert.equal((await send(`${path}/${g.id}`,"PATCH",{title:"Simulator Sessions",description:"no"})).status,409);
  assert.equal((await (await app.request(`${path}/${g.id}`)).json()).title,"New Group");
  const m = "/v1/convai/realtime/conversations/sim-realtime-conversation/conversation-group";
  assert.equal((await send(m,"PUT",{conversation_group_id:g.id})).status,200);
  assert.equal((await send(m,"PUT",{conversation_group_id:"unknown"})).status,404);
  assert.equal((await send(m.replace("sim-realtime-conversation","unknown"),"DELETE")).status,404);
  assert.equal((await send(m,"DELETE")).status,200); assert.equal((await send(m,"DELETE")).status,200);
  assert.equal((await send(`${path}/${g.id}`,"DELETE")).status,200);
  assert.equal((await app.request(`${path}/${g.id}`)).status,404);
  assert.equal((await send(`${path}/${g.id}`,"PATCH",{})).status,404);
  assert.equal((await send(`${path}/${g.id}`,"DELETE")).status,404);
  assert.equal((await app.request(`${path}?cursor=no`)).status,400);
  assert.equal((await app.request(`${path}?page_size=101`)).status,400);
  assert.equal((await (await second.request(path)).json()).conversation_groups.length,2);
  await app.scenario("emptyRealtimeGroups","api");
  assert.equal((await (await app.request(path)).json()).conversation_groups.length,0);
  assert.equal((await send(m,"DELETE")).status,404);
  await app.scenario("reset","api");
  assert.equal((await (await app.request(path)).json()).conversation_groups.length,2);
  assert.equal((await (await send(path,"POST",{title:"Restored"})).json()).id,g.id);
});
