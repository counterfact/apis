import assert from "node:assert/strict";
import test from "node:test";
import { createDispatcherHarness } from "../test-support/dispatcher.js";
import { createScenarioRunner } from "../test-support/scenarios.js";
import * as scenarios from "../api/scenarios/index.js";
import { Context } from "../api/routes/audio-native/_.context.js";
const url = "https://simulator.invalid/articles/local";
const settings = "/v1/audio-native/sim-project/settings";
const post = (body: unknown) => ({ method: "POST", headers: {"content-type":"application/json"}, body: JSON.stringify(body) });
test("AudioNative context shares Studio state, copies captures, completes once and resets", async () => {
  const empty = new Context();
  assert.equal(empty.players.size, 0); assert.equal(empty.articles.size, 0); assert.equal(empty.pending.size, 0);
  const r = await createScenarioRunner(); await r.run(scenarios.startup);
  const c = r.loadContext("/audio-native") as unknown as Context;
  const studio = r.loadContext("/studio/projects");
  const baseline = c.settings("sim-project"); baseline.settings!.title = "mutated response";
  assert.equal(c.settings("sim-project").settings!.title, "Local article");
  const before = structuredClone(studio.projects);
  for (const body of [{url:"unknown"},{url,title:42},{url,extra:true}]) assert.throws(() => c.update(body));
  assert.deepEqual(studio.projects, before); assert.equal(c.pending.size,0);
  studio.projects.get("sim-project")!.metadata.volume_normalization = true;
  const invalid = structuredClone(studio.projects); assert.throws(() => c.update({url})); assert.deepEqual(studio.projects, invalid);
  studio.projects.get("sim-project")!.metadata.volume_normalization = false;
  r.context.voices.delete("sim-narrator"); assert.throws(() => c.update({url})); assert.equal(c.pending.size,0);
  await r.run(scenarios.reset);
  const body = {url,title:"Changed title",author:"Changed author"}; c.update(body);
  body.title = "changed input"; c.articles.get(url)!.text = "changed fixture";
  assert.equal(c.pending.get("sim-project")!.title,"Changed title");
  assert.throws(() => c.update({url})); assert.throws(() => studio.updateChapter("sim-project","sim-audio-native-chapter",{name:"Busy"}));
  await r.run(scenarios.completeAudioNative);
  const ready = c.settings("sim-project"); assert.equal(ready.settings!.status,"ready"); assert.ok(ready.snapshot_id);
  assert.equal(studio.get("sim-project").title,"Changed title");
  const snapshot = studio.snapshot("sim-project",ready.snapshot_id!);
  assert.equal(snapshot.character_alignments[0].characters.join(""),"Changed title\nChanged author\nLocal synthetic article.");
  await r.run(scenarios.completeAudioNative); assert.equal(studio.snapshots.size,1);
  await r.run(scenarios.reset); c.update({url}); studio.deleteProject("sim-project");
  assert.throws(() => c.settings("sim-project")); await r.run(scenarios.completeAudioNative); assert.equal(c.pending.size,0); assert.equal(studio.snapshots.size,0);
  await r.run(scenarios.reset); assert.equal(c.pending.size,0); assert.equal(c.settings("sim-project").snapshot_id,null);
  const other = await createScenarioRunner(); await other.run(scenarios.startup);
  c.update({url}); assert.equal((other.loadContext("/audio-native") as unknown as Context).pending.size,0);
});
test("AudioNative Dispatcher validates requests and exposes canonical conversion and publication", async () => {
  const h = await createDispatcherHarness();
  let res = await h.request(settings); assert.equal(res.status,200); assert.equal((await res.json()).settings.title,"Local article");
  for (const body of [{},{url:42},{url:"unknown"},{url,extra:true}]) {
    res = await h.request("/v1/audio-native/content",post(body)); assert.equal(res.status,400);
  }
  assert.equal((await h.request("/v1/audio-native/missing/settings")).status,404);
  res = await h.request("/v1/audio-native/content",post({url})); assert.equal(res.status,200);
  assert.deepEqual(await res.json(),{project_id:"sim-project",converting:true,publishing:true,html_snippet:"<div id='audio-native-player'></div>"});
  assert.equal((await (await h.request(settings)).json()).settings.status,"processing");
  assert.equal((await h.request("/v1/audio-native/content",post({url}))).status,409);
  await h.scenario("completeAudioNative");
  res = await h.request(settings); const ready = await res.json(); assert.equal(res.status,200); assert.equal(ready.settings.status,"ready"); assert.ok(ready.snapshot_id); assert.equal(ready.settings.audio_url,null);
  res = await h.request(`/v1/studio/projects/sim-project/snapshots/${ready.snapshot_id}`); assert.equal(res.status,200);
  assert.equal((await res.json()).character_alignments[0].characters.join(""),"Local article\nLocal author\nLocal synthetic article.");
  await h.scenario("completeAudioNative");
  res = await h.request("/v1/audio-native/content",post({url,title:"",author:null})); assert.equal(res.status,200);
  await h.scenario("completeAudioNative"); assert.equal((await (await h.request(settings)).json()).settings.title,"");
  await h.request("/v1/studio/projects/sim-project",{method:"DELETE"});
  assert.equal((await h.request(settings)).status,404); assert.equal((await h.request("/v1/audio-native/content",post({url}))).status,404);
  await h.scenario("reset"); assert.equal((await (await h.request(settings)).json()).snapshot_id,null);
});
test("AudioNative owns only its publication queue and can repopulate blank Studio content", async () => {
  const r = await createScenarioRunner(); await r.run(scenarios.startup);
  const c = r.loadContext("/audio-native"), studio = r.loadContext("/studio/projects");
  const other = studio.podcast({model_id:"eleven_multilingual_v2",mode:{type:"bulletin",bulletin:{host_voice_id:"sim-narrator"}},source:{type:"text",text:"Unrelated conversion."}}).project.project_id;
  const job = structuredClone(studio.pending.get(other));
  assert.deepEqual(c.settings(other), {enabled:false,snapshot_id:null,settings:null});
  studio.blankContent("sim-project",undefined); c.update({url});
  await r.run(scenarios.completeAudioNative);
  assert.deepEqual(studio.pending.get(other),job); assert.equal(studio.get(other).state,"converting");
  assert.equal(studio.listSnapshots(other).snapshots.length,0);
  const published = c.settings("sim-project").snapshot_id!;
  const snapshot = studio.snapshot("sim-project",published);
  const media = studio.snapshotAudio("sim-project",published,{});
  c.update({url,title:"Replacement"});
  assert.equal(c.settings("sim-project").snapshot_id,published);
  assert.deepEqual(studio.snapshot("sim-project",published),snapshot);
  assert.deepEqual(studio.snapshotAudio("sim-project",published,{}),media);
  await r.run(scenarios.emptyAudioNative);
  assert.equal(c.pending.size,0); assert.equal(c.players.size,0);
  // Removing player configuration does not cancel or mutate a canonical Studio job.
  assert.equal(studio.pending.size,2); assert.deepEqual(studio.pending.get(other),job);
  await r.run(scenarios.completeAudioNative); assert.equal(studio.pending.size,2);
  await r.run(scenarios.completeStudioConversions); assert.equal(studio.pending.size,0);
  assert.equal(studio.snapshots.size,3);
  await r.run(scenarios.reset); assert.equal(studio.snapshots.size,0); assert.equal(c.settings("sim-project").snapshot_id,null);
});
