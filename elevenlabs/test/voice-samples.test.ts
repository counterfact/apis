import assert from "node:assert/strict";
import test from "node:test";
import { createHash } from "node:crypto";
import { Context } from "../api/routes/voices/pvc/_.context.js";
import { createScenarioRunner } from "../test-support/scenarios.js";
import { createDispatcherHarness } from "../test-support/dispatcher.js";
import * as scenarios from "../api/scenarios/index.js";

const hash = (bytes: Uint8Array) => createHash("sha256").update(bytes).digest("hex");
test("sample context owns atomic metadata, captured separation/training and cleanup", async () => {
  const empty = new Context();
  assert.equal(empty.sampleAudio.size, 0);
  assert.equal(empty.separation.size, 0);
  assert.equal(empty.training.size, 0);
  assert.equal(empty.challenge, undefined);
  const r = await createScenarioRunner();
  await r.run(scenarios.startup);
  await r.run(scenarios.voiceSampleFixtures);
  const c = r.loadContext("/voices/pvc");
  const v = "sim-pvc-samples", s = "sim-sample";
  const bytes = c.audio(v,s);
  assert.equal(bytes.length,8340);
  assert.equal(hash(bytes),"5a8c648164ba405f8ddd927c3fa307e83410cedcf2ada38d4b1b14b18d0c7856");
  bytes.fill(1); assert.notEqual(hash(c.audio(v,s)),hash(bytes));
  for (const body of [{remove_background_noise:true},{trim_start_time:1},{trim_end_time:1},{selected_speaker_ids:["missing"]},{file_name:" "}]) assert.throws(()=>c.updateSample(v,s,body));
  assert.equal(r.context.getVoice(v)!.samples![0].file_name,"synthetic-silence.mp3");
  assert.throws(()=>c.audio("missing",s),{code:"voice_not_found"});
  assert.throws(()=>c.waveform(v,"missing"),{code:"sample_not_found"});
  assert.throws(()=>c.captcha("sim-narrator"),{code:"voice_not_professional"});
  c.updateSample(v,s,{file_name:"renamed.mp3",trim_start_time:0,trim_end_time:23040/44100*1000,remove_background_noise:false});
  assert.equal(r.context.getVoice(v)!.samples![0].file_name,"renamed.mp3");
  assert.equal(c.speakers(v,s).status,"not_started");
  c.separate(v,s);
  assert.throws(()=>c.separate(v,s),{code:"sample_busy"});
  assert.throws(()=>c.updateSample(v,s,{file_name:"locked"}),{code:"sample_busy"});
  await r.run(scenarios.completeVoiceSampleSeparation);
  assert.equal(c.speakers(v,s).status,"completed");
  await r.run(scenarios.completeVoiceSampleSeparation);
  const speakers=c.speakers(v,s); speakers.speakers!["sim-speaker"].duration_secs=99;
  assert.equal(c.speakers(v,s).speakers!["sim-speaker"].duration_secs,23040/44100);
  const selected=["sim-speaker"];
  c.updateSample(v,s,{selected_speaker_ids:selected}); selected.push("bad");
  assert.deepEqual(c.speakers(v,s).selected_speaker_ids,["sim-speaker"]);
  assert.equal(Buffer.from(c.speakerAudio(v,s,"sim-speaker").audio_base_64,"base64").length,8340);
  assert.throws(()=>c.train(v,{}),{code:"voice_not_verified"});
  await r.run(scenarios.verifiedVoiceSampleFixtures);
  c.updateSample(v,s,{selected_speaker_ids:[]});
  assert.throws(()=>c.train(v,{}),{code:"sample_has_no_selected_speakers"});
  assert.equal(c.training.size,0);
  c.updateSample(v,s,{selected_speaker_ids:["sim-speaker"]});
  assert.throws(()=>c.train(v,{model_id:"music_v1"}),{code:"unsupported_training_model"});
  c.train(v,{});
  assert.equal(r.context.getVoice(v)!.fine_tuning!.state.eleven_multilingual_v2,"queued");
  assert.throws(()=>c.deleteSample(v,s),{code:"voice_training_pending"});
  assert.throws(()=>c.update(v,{language:"es"}),{code:"voice_training_pending"});
  await r.run(scenarios.completeVoiceSampleTraining);
  await r.run(scenarios.completeVoiceSampleTraining);
  assert.equal(r.context.getVoice(v)!.fine_tuning!.state.eleven_multilingual_v2,"fine_tuned");
  assert.equal(c.training.get(v)!.samples[0].file_name,"renamed.mp3");
  c.updateSample(v,s,{file_name:"after.mp3"});
  assert.equal(c.training.get(v)!.samples[0].file_name,"renamed.mp3");
  c.deleteSample(v,s); assert.deepEqual(r.context.getVoice(v)!.samples,[]);
  assert.throws(()=>c.audio(v,s),{code:"sample_not_found"});
  assert.throws(()=>c.train(v,{}),{code:"voice_has_no_samples"});
  r.context.deleteVoice(v); assert.equal(c.training.has(v),false);
  await r.run(scenarios.voiceSampleFixtures);
  c.separate(v,s); r.context.deleteVoice(v);
  await r.run(scenarios.completeVoiceSampleSeparation);
  assert.equal(c.sampleAudio.has(v),false); assert.equal(c.separation.has(v),false);
  await r.run(scenarios.voiceSampleFixtures);
  await r.run(scenarios.verifiedVoiceSampleFixtures);
  c.train(v,{}); r.context.deleteVoice(v);
  await r.run(scenarios.completeVoiceSampleTraining);
  assert.equal(c.training.has(v),false);
  await r.run(scenarios.reset); assert.equal(c.sampleAudio.size,0); assert.equal(c.training.size,0);
});

test("sample Dispatcher validates eleven routes, canonical state, errors and reset", async()=>{
  const h=await createDispatcherHarness(); await h.scenario("voiceSampleFixtures");
  const v="sim-pvc-samples", s="sim-sample", base=`/v1/voices/pvc/${v}`, sample=`${base}/samples/${s}`;
  const post=async(path:string,body?:unknown,status=200)=>{
    const res=await h.request(path,{method:"POST",...(body===undefined?{}:{headers:{"content-type":"application/json"},body:JSON.stringify(body)})});
    assert.equal(res.status,status,await res.clone().text()); return res;
  };
  let res=await h.request(`/v1/voices/${v}/samples/${s}/audio`);
  assert.equal(res.status,200); assert.equal(res.headers.get("content-type"),"audio/mpeg"); assert.equal((await res.arrayBuffer()).byteLength,8340);
  res=await h.request(`${sample}/audio`); assert.equal(res.status,200); assert.equal((await res.json()).media_type,"audio/mpeg");
  assert.equal((await h.request(`${sample}/audio?remove_background_noise=true`)).status,400);
  assert.deepEqual((await (await h.request(`${sample}/waveform`)).json()).visual_waveform,new Array(20).fill(0));
  await post(sample,{file_name:"changed.mp3"});
  assert.equal((await (await h.request(`/v1/voices/${v}`)).json()).samples[0].file_name,"changed.mp3");
  await post(sample,{file_name:3},400); await post(sample,{remove_background_noise:true},400);
  await post(`${sample}/separate-speakers`);
  assert.equal((await (await h.request(`${sample}/speakers`)).json()).status,"pending");
  assert.equal((await h.request(`${sample}/speakers/sim-speaker/audio`)).status,409);
  await h.scenario("completeVoiceSampleSeparation");
  assert.equal((await (await h.request(`${sample}/speakers`)).json()).status,"completed");
  assert.equal((await h.request(`${sample}/speakers/sim-speaker/audio`)).status,200);
  assert.equal((await h.request(`${sample}/speakers/missing/audio`)).status,404);
  res=await h.request(`${base}/captcha`); assert.equal(res.status,200); assert.match(await res.text(),/synthetic/);
  await post(`${base}/train`,{},409); await h.scenario("verifiedVoiceSampleFixtures");
  await post(`${base}/train`,{model_id:"unknown"},400); await post(`${base}/train`,{});
  await post(`${base}/train`,{},409); await h.scenario("completeVoiceSampleTraining");
  assert.equal((await (await h.request(`/v1/voices/${v}`)).json()).fine_tuning.state.eleven_multilingual_v2,"fine_tuned");
  assert.equal((await h.request(sample,{method:"DELETE"})).status,200);
  assert.equal((await h.request(`${sample}/audio`)).status,404);
  assert.equal((await h.request(`/v1/voices/sim-narrator/samples/sim-regular-sample`,{method:"DELETE"})).status,200);
  assert.equal((await h.request(`/v1/voices/sim-narrator/samples/sim-regular-sample/audio`)).status,404);
  assert.equal((await h.request("/v1/voices/pvc/missing/captcha")).status,404);
  await h.scenario("reset"); assert.equal((await h.request(`${base}/captcha`)).status,404);
  await h.scenario("voiceSampleFixtures");
  assert.equal((await h.request(`/v1/voices/${v}`,{method:"DELETE"})).status,200);
  assert.equal((await h.request(`${sample}/audio`)).status,404);
  const other=await createDispatcherHarness(); assert.equal((await other.request(`${sample}/audio`)).status,404);
  await h.scenario("voiceSampleFixtures"); await h.scenario("emptyPvcVoices");
  res=await h.request("/v1/voices/sim-narrator/samples/sim-regular-sample/audio");
  assert.equal(res.status,200); assert.equal((await res.arrayBuffer()).byteLength,8340);
});
