import assert from 'node:assert/strict';
import test from 'node:test';
import { createDispatcherHarness } from '../test-support/dispatcher.js';
import { createScenarioRunner } from '../test-support/scenarios.js';
import * as scenarios from '../api/scenarios/index.js';
const base = '/v1/convai/triage-tickets', agent = '/v1/convai/agents/sim-agent/triage-tickets';
test('triage context empty state, atomic merge, histories and reset', async () => {
    const { Context } = await import('../api/routes/convai/triage-tickets/_.context.js');
    assert.equal(new Context().tickets.size, 0);
    const r = await createScenarioRunner();
    await r.run(scenarios.startup);
    const c = r.loadContext('/convai/triage-tickets');
    const a = c.createManual('sim-agent', { qa_comment: 'Check instructions', priority: 'low' }), b = c.createManual('sim-agent', { qa_comment: 'Urgent follow-up', priority: 'urgent' });
    assert.throws(() => c.merge(a.agentqa_ticket_id, { source_ticket_ids: [b.agentqa_ticket_id, 'missing'] }));
    assert.equal(c.get(b.agentqa_ticket_id).status, 'open');
    assert.equal(c.merge(a.agentqa_ticket_id, { source_ticket_ids: [b.agentqa_ticket_id] }).priority, 'urgent');
    assert.equal(c.get(b.agentqa_ticket_id).merged_into_ticket_id, a.agentqa_ticket_id);
    assert.throws(() => c.patch(b.agentqa_ticket_id, { status: 'open' }));
    assert.throws(() => c.merge(a.agentqa_ticket_id, { source_ticket_ids: [a.agentqa_ticket_id] }));
    const copy = c.get(a.agentqa_ticket_id);
    copy.labels.push('mutated');
    assert.deepEqual(c.get(a.agentqa_ticket_id).labels, []);
    assert.throws(() => c.patch(a.agentqa_ticket_id, { assignee_user_id: 'missing' }));
    c.patch(a.agentqa_ticket_id, { priority: null, status: 'resolved' });
    assert.equal(c.get(a.agentqa_ticket_id).priority, null);
    const foreign = structuredClone(c.get(a.agentqa_ticket_id));
    foreign.agentqa_ticket_id = 'foreign';
    foreign.agent_id = 'another-agent';
    foreign.status = 'open';
    c.tickets.set('foreign', foreign);
    assert.throws(() => c.merge(a.agentqa_ticket_id, { source_ticket_ids: ['foreign'] }));
    assert.equal(c.get('foreign').status, 'open');
    assert.throws(() => c.delete(a.agentqa_ticket_id));
    c.delete(b.agentqa_ticket_id);
    c.delete(a.agentqa_ticket_id);
    assert.throws(() => c.get(a.agentqa_ticket_id));
    const manual = c.createManual('sim-agent', { qa_comment: 'Valid' });
    const before = c.get(manual.agentqa_ticket_id);
    for (const bad of [{ title: 3 }, { priority: 'unknown' }, { status: 'merged' }, { qa_comment: '' }])
        assert.throws(() => c.patch(manual.agentqa_ticket_id, bad));
    assert.deepEqual(c.get(manual.agentqa_ticket_id), before);
    const conversation = c.create({ conversation_id: 'sim-conversation', qa_comment: 'Transfer me' });
    const mergedConversation = c.merge(manual.agentqa_ticket_id, { source_ticket_ids: [conversation.agentqa_ticket_id] });
    assert.deepEqual(mergedConversation.conversation_ids, ['sim-conversation']);
    assert.deepEqual(c.get(conversation.agentqa_ticket_id).conversation_ids, []);
    assert.equal(r.loadContext('/convai/conversations').conversations.has('sim-conversation'), true);
    const members = r.loadContext('/workspace/groups');
    members.members.clear();
    assert.deepEqual(c.users('sim-agent'), []);
    assert.throws(() => c.patch(manual.agentqa_ticket_id, { assignee_user_id: 'sim-member-narrator' }));
    const agents = r.loadContext('/convai/agents');
    agents.agents.delete('sim-agent');
    assert.throws(() => c.createManual('sim-agent', { qa_comment: 'Gone' }));
    await r.run(scenarios.reset);
    assert.equal(c.tickets.size, 1);
    assert.equal(c.nextId, 1);
});
test('triage Dispatcher lifecycle, filtering, comments, merge, validation and isolation', async () => {
    const app = await createDispatcherHarness(), other = await createDispatcherHarness();
    const send = (p: string, m: string, b?: unknown) => app.request(p, { method: m, ...(b === undefined ? {} : { headers: { 'content-type': 'application/json' }, body: JSON.stringify(b) }) });
    const initial = await app.request(base);
    assert.equal(initial.status, 200);
    assert.equal((await initial.json()).agent_conversation_tickets.length, 1);
    const response = await send(base, 'POST', { conversation_id: 'sim-conversation', qa_comment: 'Wrong information', turn_comments: [{ turn_index: 0, comment: 'Greeting issue' }], priority: 'high' });
    assert.equal(response.status, 200);
    const ticket = await response.json();
    assert.equal(ticket.agent_id, 'sim-agent');
    const repeat = await send(base, 'POST', { conversation_id: 'sim-conversation', qa_comment: 'More evidence', priority: 'urgent' });
    assert.equal(repeat.status, 200);
    assert.equal((await repeat.json()).agentqa_ticket_id, ticket.agentqa_ticket_id);
    const manual = await send(agent, 'POST', { qa_comment: 'Update knowledge', priority: 'low' });
    assert.equal(manual.status, 200);
    const id = (await manual.json()).agentqa_ticket_id;
    const patched = await send(`${base}/${id}`, 'PATCH', { title: 'New title', assignee_user_id: 'sim-member-narrator', status: 'in_progress' });
    assert.equal(patched.status, 200);
    assert.equal((await patched.json()).assignee_user_id, 'sim-member-narrator');
    assert.equal((await send(`${base}/${id}/comments`, 'POST', { comment: 'Resolution discussion' })).status, 200);
    assert.equal((await send(`${base}/${ticket.agentqa_ticket_id}/turn-comments`, 'POST', { turn_index: 0, comment: 'Needs careful wording' })).status, 200);
    assert.equal((await send(`${base}/${id}/turn-comments`, 'POST', { turn_index: 0, comment: 'Not backed' })).status, 400);
    const hits = await (await app.request(`${agent}?sources=manual&search=resolution&assignee_user_id=sim-member-narrator`)).json();
    assert.equal(hits.agent_conversation_tickets.length, 1);
    assert.equal(hits.agent_conversation_tickets[0].search_match.field, 'comment');
    const page = await (await app.request(`${base}?page_size=1&sort_by=priority`)).json();
    assert.equal(page.agent_conversation_tickets[0].priority, 'urgent');
    assert.equal(page.has_more, true);
    assert.equal((await app.request(`${base}?cursor=${page.next_cursor}`)).status, 200);
    assert.equal((await send(`${base}/${ticket.agentqa_ticket_id}/merge`, 'POST', { source_ticket_ids: ['sim-ticket'] })).status, 200);
    assert.equal((await (await app.request(`${base}/sim-ticket`)).json()).status, 'merged');
    const users = await app.request(`${agent}/assignable-users`);
    assert.equal(users.status, 200);
    assert.equal((await users.json()).length, 2);
    for (const [p, m, b, status] of [[base, 'POST', { conversation_id: 'missing' }, 404], [`${base}/${id}`, 'PATCH', { assignee_user_id: 'missing' }, 400], [`${base}/${id}/comments`, 'POST', { comment: '' }, 400], [`${base}/${id}`, 'PATCH', { status: 'merged' }, 400], [`${base}/${ticket.agentqa_ticket_id}/merge`, 'POST', { source_ticket_ids: [id, id] }, 400]] as const)
        assert.equal((await send(p, m, b)).status, status);
    for (const q of ['page_size=0', 'sources=bad', 'cursor=bad'])
        assert.equal((await app.request(`${base}?${q}`)).status, 400);
    const deleted = await send(`${base}/${id}`, 'DELETE');
    assert.equal(deleted.status, 204);
    assert.equal(await deleted.text(), '');
    assert.equal((await app.request(`${base}/${id}`)).status, 404);
    assert.equal((await (await other.request(base)).json()).agent_conversation_tickets.length, 1);
    await app.scenario('emptyTriageTickets', 'api');
    assert.equal((await (await app.request(base)).json()).agent_conversation_tickets.length, 0);
    await app.scenario('reset', 'api');
    assert.equal((await (await app.request(base)).json()).agent_conversation_tickets.length, 1);
});
