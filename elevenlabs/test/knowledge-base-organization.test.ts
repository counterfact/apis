import assert from "node:assert/strict";
import test from "node:test";
import { createDispatcherHarness } from "../test-support/dispatcher.js";
import { createScenarioRunner } from "../test-support/scenarios.js";
import * as scenarios from "../api/scenarios/index.js";
const base="/v1/convai/knowledge-base";
test("knowledge organization context atomic moves independent deletes live dependencies and size",async()=>{
  const runner=await createScenarioRunner();await runner.run(scenarios.startup);
  const c=runner.loadContext("/convai/knowledge-base");
  const folder=c.createFolder({name:"Destination"});
  const nested=c.createFolder({name:"Nested",parent_folder_id:"sim-kb-folder"});
  assert.throws(()=>c.moveDocuments({document_ids:["sim-kb-text","missing"],move_to:folder.id}));
  assert.equal(c.getDocument("sim-kb-text").folder_parent_id,"sim-kb-folder");
  assert.throws(()=>c.moveDocuments({document_ids:["sim-kb-folder"],move_to:nested.id}));
  assert.throws(()=>c.moveDocuments({document_ids:["sim-kb-folder"],move_to:"sim-kb-folder"}));
  c.moveDocuments({document_ids:["sim-kb-text",nested.id],move_to:folder.id});
  assert.deepEqual(c.folderPath("sim-kb-text").map(p=>p.id),[folder.id]);
  assert.equal((c.getDocument(folder.id) as {children_count:number}).children_count,2);
  c.moveDocument("sim-kb-text",{});assert.equal(c.getDocument("sim-kb-text").folder_parent_id,null);
  await runner.run(scenarios.knowledgeBaseReferences);
  const agents=runner.loadContext("/convai/agents");const duplicate=agents.duplicateAgent("sim-agent",{});
  assert.equal(c.listDependentAgents(["sim-kb-text"],{page_size:1}).has_more,true);
  assert.equal(c.agentKnowledgeSize("sim-agent").number_of_pages,1);
  agents.agents.get("sim-agent")!.configuration.conversation_config.agent!.prompt!.knowledge_base=[{id:folder.id,name:"Destination",type:"folder"}];
  c.moveDocument("sim-kb-text",{move_to:folder.id});
  assert.deepEqual(c.listDependentAgents(["sim-kb-text"],{dependent_type:"transitive"}).agents.map(a=>a.id),["sim-agent"]);
  assert.equal(c.agentKnowledgeSize("sim-agent").number_of_pages,1);
  const unused=c.createFolder({name:"Unused"});
  const result=c.bulkDelete({document_ids:["sim-kb-text","missing",unused.id]});
  assert.equal(result["sim-kb-text"].status,"failure");assert.equal(result.missing.status,"failure");assert.equal(result[unused.id].status,"success");
  c.bulkDelete({document_ids:["sim-kb-text"],force:true});
  assert.ok(duplicate.value);
  assert.equal(c.agentKnowledgeSize(duplicate.value.agent_id).number_of_pages,0);
  assert.equal(c.agentKnowledgeSize("sim-agent").number_of_pages,0);
  const overlap=c.createFolder({name:"Overlap"});const child=c.createText({text:"Child",parent_folder_id:overlap.id});
  const overlapping=c.bulkDelete({document_ids:[overlap.id,child.id],force:true});
  assert.equal(overlapping[overlap.id].status,"success");assert.equal(overlapping[child.id].status,"success");
  for(const q of [{dependent_type:"bad"},{cursor:"bad"},{page_size:0}])assert.throws(()=>c.listDependentAgents([folder.id],q));
  assert.throws(()=>c.agentKnowledgeSize("missing"));
  assert.throws(()=>c.moveDocuments({document_ids:["sim-kb-folder","sim-kb-folder"]}));
  await runner.run(scenarios.reset);assert.equal(c.documents.size,2);
});
test("knowledge organization Dispatcher moves batch results dependencies size and reset",async()=>{
  const app=await createDispatcherHarness();
  const send=(url:string,body:unknown)=>app.request(url,{method:"POST",headers:{"content-type":"application/json"},body:JSON.stringify(body)});
  const moving=await send(`${base}/sim-kb-text/move`,{});assert.equal(moving.status,200);assert.equal(await moving.text(),"");
  assert.equal((await(await app.request(`${base}/sim-kb-text`)).json()).folder_parent_id,null);
  const folder=await(await send(`${base}/folder`,{name:"Destination"})).json();
  const fail=await send(`${base}/bulk-move`,{document_ids:["sim-kb-text","missing"],move_to:folder.id});assert.equal(fail.status,404);
  assert.equal((await(await app.request(`${base}/sim-kb-text`)).json()).folder_parent_id,null);
  assert.equal((await send(`${base}/bulk-move`,{document_ids:["sim-kb-text"],move_to:folder.id})).status,200);
  assert.equal((await(await app.request(`${base}/${folder.id}`)).json()).children_count,1);
  assert.equal((await send(`${base}/${folder.id}/move`,{move_to:folder.id})).status,400);
  await app.scenario("knowledgeBaseReferences","api");
  const deps=await app.request(`${base}/sim-kb-text/dependent-agents?page_size=1`);assert.equal(deps.status,200);assert.equal((await deps.json()).agents[0].id,"sim-agent");
  const batch=await send(`${base}/dependent-agents`,{document_ids:["sim-kb-text",folder.id]});assert.equal(batch.status,200);assert.equal((await batch.json()).agents.length,1);
  const size=await app.request("/v1/convai/agent/sim-agent/knowledge-base/size");assert.equal(size.status,200);assert.deepEqual(await size.json(),{number_of_pages:1});
  const deletion=await send(`${base}/bulk-delete`,{document_ids:["missing","sim-kb-text"]});assert.equal(deletion.status,200);const results=await deletion.json();assert.equal(results.missing.status,"failure");assert.equal(results["sim-kb-text"].error_code,409);
  const force=await send(`${base}/bulk-delete`,{document_ids:["sim-kb-text"],force:true});assert.equal(force.status,200);assert.deepEqual((await force.json())["sim-kb-text"],{status:"success",data:{id:"sim-kb-text"}});
  assert.deepEqual(await(await app.request("/v1/convai/agent/sim-agent/knowledge-base/size")).json(),{number_of_pages:0});
  assert.equal((await app.request(`${base}/missing/dependent-agents`)).status,404);
  assert.equal((await app.request(`${base}/${folder.id}/dependent-agents?dependent_type=bad`)).status,400);
  assert.equal((await send(`${base}/bulk-move`,{document_ids:[]})).status,400);
  assert.equal((await send(`${base}/bulk-delete`,{document_ids:[folder.id,folder.id]})).status,400);
  assert.equal((await app.request("/v1/convai/agent/missing/knowledge-base/size")).status,404);
  await app.scenario("reset","api");assert.equal((await(await app.request(base)).json()).documents.length,2);
});
