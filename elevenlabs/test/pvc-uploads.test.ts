import assert from "node:assert/strict";
import test from "node:test";
import { createScenarioRunner } from "../test-support/scenarios.js";
import { createDispatcherHarness } from "../test-support/dispatcher.js";
import * as scenarios from "../api/scenarios/index.js";
const file = (contentType = "audio/mpeg") => ({data:new Uint8Array([255,251,144,100]),filename:"synthetic.mp3",contentType,size:4});
test("PVC upload context validates atomically and preserves synthetic verification state", async()=>{
 const r=await createScenarioRunner(); await r.run(scenarios.startup);
 const c=r.loadContext("/voices/pvc"), id=c.create({name:"Professional",language:"en"}).voice_id;
 const f=file(), added=c.addSamples(id,{files:[f]}); assert.equal(added.length,1);
 f.data.fill(0); added[0].file_name="mutated";
 assert.deepEqual(c.audio(id,added[0].sample_id),new Uint8Array([255,251,144,100]));
 assert.equal(r.context.getVoice(id)!.samples![0].file_name,"synthetic.mp3");
 const before=r.context.getVoice(id);
 for(const body of [{files:[]},{files:[file(),file("text/plain")]},{files:[file()],remove_background_noise:true}]) assert.throws(()=>c.addSamples(id,body));
 assert.deepEqual(r.context.getVoice(id),before);
 assert.throws(()=>c.addSamples(id,{files:Array.from({length:20},()=>file())}),{code:"sample_limit_exceeded"});
 assert.equal(c.nextSample,1);
 assert.throws(()=>c.addSamples(id,{files:[{...file(),size:99}]}),{code:"invalid_upload"});
 assert.throws(()=>c.addSamples(id,{files:[{...file(),data:new Uint8Array(10*1024*1024+1),size:10*1024*1024+1}]}));
 assert.throws(()=>c.separate(id,added[0].sample_id),{code:"sample_duration_unavailable"});
 const denied=c.create({name:"Unowned",language:"en"}).voice_id;
 r.context.voices.get(denied)!.is_owner=false;
 for(const action of [()=>c.addSamples(denied,{files:[file()]}),()=>c.submitCaptcha(denied,{recording:file()}),()=>c.requestVerification(denied,{files:[file("application/pdf")]} )]) assert.throws(action,{code:"voice_not_owned"});
 assert.throws(()=>c.requestVerification(id,{files:[],extra_text:"test"}));
 assert.throws(()=>c.requestVerification(id,{files:[file("application/pdf")],extra_text:"x".repeat(5001)}));
 assert.equal(c.verificationRequests.size,0);
 assert.throws(()=>c.addSamples("sim-narrator",{files:[file()]}),{code:"voice_not_professional"});
 c.submitCaptcha(id,{recording:file()}); assert.equal(r.context.getVoice(id)!.fine_tuning!.verification_attempts_count,1);
 assert.equal(r.context.getVoice(id)!.fine_tuning!.is_allowed_to_fine_tune,false);
 assert.throws(()=>c.submitCaptcha(id,{recording:file()}),{code:"verification_pending"});
 const doc=file("application/pdf"); c.requestVerification(id,{files:[doc],extra_text:"Synthetic evidence"}); doc.data.fill(0);
 assert.equal(r.context.getVoice(id)!.fine_tuning!.manual_verification_requested,true);
 assert.equal(c.verificationRequests.get(id)!.files[0].data[0],255);
 assert.throws(()=>c.requestVerification(id,{files:[file("application/pdf")]}),{code:"verification_pending"});
 await r.run(scenarios.completePvcVerification);
 assert.equal(r.context.getVoice(id)!.fine_tuning!.is_allowed_to_fine_tune,true);
 assert.equal(r.context.getVoice(id)!.fine_tuning!.manual_verification_requested,false);
 r.context.models.get("eleven_multilingual_v2")!.can_be_finetuned=true;
 c.train(id,{}); assert.throws(()=>c.addSamples(id,{files:[file()]}),{code:"voice_training_pending"});
 assert.throws(()=>c.submitCaptcha(id,{recording:file()}),{code:"voice_training_pending"});
 r.context.deleteVoice(id); assert.equal(c.verificationRequests.has(id),false); assert.equal(c.captchaRequests.has(id),false);
 const pending=c.create({name:"Pending",language:"en"}).voice_id;
 c.submitCaptcha(pending,{recording:file()}); c.requestVerification(pending,{files:[file("application/pdf")]});
 r.context.deleteVoice(pending); await r.run(scenarios.completePvcVerification);
 assert.equal(c.captchaRequests.has(pending),false); assert.equal(c.verificationRequests.has(pending),false);
 await r.run(scenarios.reset); assert.equal(c.nextSample,0); assert.equal(c.verificationRequests.size,0);
});
test("PVC multipart Dispatcher uploads samples and accepts verification submissions",async()=>{
 const h=await createDispatcherHarness();
 const created=await h.request("/v1/voices/pvc",{method:"POST",headers:{"content-type":"application/json"},body:JSON.stringify({name:"Uploaded",language:"en"})});
 const id=(await created.json()).voice_id, base=`/v1/voices/pvc/${id}`;
 const post=async(path:string,body:Record<string,unknown>,status=200)=>{const res=await h.requestMultipart(path,body); assert.equal(res.status,status,await res.clone().text()); return res;};
 const added=await (await post(`${base}/samples`,{files:[file()]})).json(); assert.equal(added.length,1); assert.equal(added[0].mime_type,"audio/mpeg"); assert.equal(added[0].size_bytes,4);
 const audio=await h.request(`/v1/voices/${id}/samples/${added[0].sample_id}/audio`); assert.equal(audio.status,200); assert.equal(audio.headers.get("content-type"),"audio/mpeg"); assert.equal((await audio.arrayBuffer()).byteLength,4);
 await post(`${base}/samples`,{},400); await post(`${base}/samples`,{files:[]},400); await post(`${base}/samples`,{files:[file()],remove_background_noise:true},400);
 await post(`${base}/captcha`,{},400); assert.deepEqual(await (await post(`${base}/captcha`,{recording:file()})).json(),{status:"ok"});
 let voice=await (await h.request(`/v1/voices/${id}`)).json(); assert.equal(voice.fine_tuning.verification_attempts_count,1); assert.equal(voice.fine_tuning.is_allowed_to_fine_tune,false);
 await post(`${base}/verification`,{files:[file()]},400);
 assert.deepEqual(await (await post(`${base}/verification`,{files:[file("application/pdf")],extra_text:"Synthetic"})).json(),{status:"ok"});
 voice=await (await h.request(`/v1/voices/${id}`)).json(); assert.equal(voice.fine_tuning.manual_verification_requested,true);
 await h.scenario("completePvcVerification"); voice=await (await h.request(`/v1/voices/${id}`)).json(); assert.equal(voice.fine_tuning.is_allowed_to_fine_tune,true);
 await post(`/v1/voices/pvc/missing/samples`,{files:[file()]},404); await post(`/v1/voices/pvc/sim-narrator/captcha`,{recording:file()},409);
 await h.scenario("reset"); await post(`${base}/verification`,{files:[file("application/pdf")]},404);
});
