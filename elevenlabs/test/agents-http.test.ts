import assert from "node:assert/strict";
import test from "node:test";
import { createDispatcherHarness } from "../test-support/dispatcher.js";
const path = "/v1/convai/agents";

test("agent Dispatcher supports list, detail, summaries, independent duplication and deletion", async () => {
  const app = await createDispatcherHarness();
  const duplicate = (id: string, body: unknown) => app.request(`${path}/${id}/duplicate`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) });
  const list = async (query = "") => {
    const response = await app.request(path + query);
    assert.equal(response.status, 200);
    assert.match(response.headers.get("content-type")!, /application\/json/);
    return response.json();
  };
  const baseline = await list();
  assert.equal(baseline.agents[0].agent_id, "sim-agent");
  const originalResponse = await app.request(path + "/sim-agent");
  assert.equal(originalResponse.status, 200);
  const original = await originalResponse.json();
  assert.equal(original.name, "Simulator Support");
  assert.deepEqual(original.conversation_config.agent.prompt.tool_ids, []);
  const response = await duplicate("sim-agent", { name: "Help Desk" });
  assert.equal(response.status, 200);
  const { agent_id: id } = await response.json();
  assert.equal(id, "sim-agent-created-1");
  const read = await app.request(`${path}/${id}`);
  assert.equal(read.status, 200);
  const copied = await read.json();
  assert.deepEqual(copied.conversation_config, original.conversation_config);
  assert.equal(copied.name, "Help Desk");
  assert.deepEqual(copied.metadata, { created_at_unix_secs: 1735689601, updated_at_unix_secs: 1735689601 });
  assert.equal((await list("?archived=false&tags=support&search=HELP")).agents[0].agent_id, id);
  assert.deepEqual((await list("?archived=true")).agents, []);
  assert.deepEqual((await list("?created_by_user_id=other")).agents, []);
  assert.equal((await list("?created_by_user_id=@me&show_only_owned_agents=true")).agents.length, 2);
  const page = await list("?page_size=1&sort_by=name&sort_direction=asc");
  assert.equal(page.agents[0].agent_id, id);
  assert.equal(page.has_more, true);
  const last = await list(`?cursor=${page.next_cursor}&page_size=1&sort_by=name&sort_direction=asc`);
  assert.equal(last.agents[0].agent_id, "sim-agent");
  assert.equal(last.has_more, false);
  assert.equal(last.next_cursor, null);
  const summaryResponse = await app.request(`${path}/summaries?agent_ids=${id}&agent_ids=sim-agent&agent_ids=missing`);
  assert.equal(summaryResponse.status, 200);
  const summaries = await summaryResponse.json();
  assert.equal(summaries[id].status, "success");
  assert.equal(summaries[id].data.voice_id, "sim-narrator");
  assert.equal(summaries[id].data.archived, false);
  assert.deepEqual(summaries[id].data.tags, ["support"]);
  assert.equal(summaries.missing.error_code, 404);
  const deletion = await app.request(path + "/sim-agent", { method: "DELETE" });
  assert.equal(deletion.status, 204);
  assert.equal(await deletion.text(), "");
  assert.equal((await app.request(path + "/sim-agent")).status, 404);
  assert.equal((await app.request(`${path}/${id}`)).status, 200);
  assert.deepEqual((await list()).agents.map((a: { agent_id: string }) => a.agent_id), [id]);
  assert.equal((await (await app.request(path + "/summaries?agent_ids=sim-agent")).json())["sim-agent"].status, "failure");
  const other = await createDispatcherHarness();
  assert.equal((await other.request(`${path}/${id}`)).status, 404);
  await app.scenario("reset");
  assert.deepEqual(await list(), baseline);
  await app.scenario("emptyAgents");
  assert.deepEqual((await list()).agents, []);
  await app.scenario("reset");
  assert.equal((await (await duplicate("sim-agent", {})).json()).agent_id, "sim-agent-created-1");
});

test("agent Dispatcher rejects unsupported selectors and invalid queries without mutation", async () => {
  const app = await createDispatcherHarness();
  const duplicate = (id: string, body: unknown) => app.request(`${path}/${id}/duplicate`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) });
  const before = await (await app.request(path + "/sim-agent")).json();
  for (const query of ["?branch_id=branch", "?version_id=version"]) assert.equal((await app.request(path + "/sim-agent" + query)).status, 404);
  assert.equal((await app.request(path + "/sim-agent?include_procedure_generated_workflow_elements=true")).status, 400);
  for (const query of ["?cursor=bad", "?page_size=0", "?page_size=101", "?sort_by=call_count_7d", "?archived=invalid"]) assert.equal((await app.request(path + query)).status, 400);
  assert.equal((await duplicate("sim-agent", { name: " " })).status, 400);
  assert.equal((await duplicate("missing", {})).status, 404);
  assert.equal((await app.request(path + "/missing", { method: "DELETE" })).status, 404);
  assert.equal((await app.request(path + "/sim-agent?force=true", { method: "DELETE" })).status, 400);
  assert.deepEqual(await (await app.request(path + "/sim-agent")).json(), before);
  const created = await duplicate("sim-agent", { name: null });
  assert.equal(created.status, 200);
  const id = (await created.json()).agent_id;
  assert.equal(id, "sim-agent-created-1");
  assert.equal((await (await app.request(`${path}/${id}`)).json()).name, "Simulator Support (copy)");
});

test("agent Dispatcher duplication preserves persisted analysis configuration", async () => {
  const app = await createDispatcherHarness();
  await app.scenario("agentAnalysisReferences");
  const original = await (await app.request(`${path}/sim-agent`)).json();
  const response = await app.request(`${path}/sim-agent/duplicate`, {method:"POST",headers:{"Content-Type":"application/json"},body:"{}"});
  assert.equal(response.status,200);
  const {agent_id} = await response.json();
  const copy = await app.request(`${path}/${agent_id}`);
  assert.equal(copy.status,200);
  assert.deepEqual((await copy.json()).platform_settings.analysis_items,original.platform_settings.analysis_items);
  assert.equal((await app.request(`${path}/${agent_id}`,{method:"DELETE"})).status,204);
  assert.deepEqual((await (await app.request(`${path}/sim-agent`)).json()).platform_settings.analysis_items,original.platform_settings.analysis_items);
});
